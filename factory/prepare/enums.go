package prepare

// 领域层的 enum 映射(DB 值 ↔ proto enum)→ 生成转换函数。
// 读取宽容: DB 里出现映射表以外的值 → 返回 UNSPECIFIED,并调用 anomaly.Report 记录指标。

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/reflect/protoregistry"

	"apifactory/factory/spec"
)

var dbIntGoType = map[string]string{"int2": "int16", "int4": "int32", "int8": "int64", "smallint": "int16", "integer": "int32", "bigint": "int64"}

type enumMapping struct {
	Table, Column string
	Helper        string // jobsStatus → jobsStatusToProto / jobsStatusToDB / jobsStatusPtrToDB
	DBGoType      string // int32
	GoType        string // jobsv1.JobStatus
	Unspecified   string // jobsv1.JobStatus_JOB_STATUS_UNSPECIFIED
	Cases         []enumCase
}

type enumCase struct {
	DB    int64
	Const string // jobsv1.JobStatus_JOB_STATUS_PENDING
}

func enumHelperName(table, column string) string {
	return lowerFirst(goCamelCase(table)) + goCamelCase(column)
}

// resolveEnum: 检查领域层的映射和 proto enum 一致,返回生成用的信息。
func resolveEnum(d *spec.Domain, table, column string, files *protoregistry.Files, cat *catalog, pbAlias, protoPkg string) (*enumMapping, error) {
	meta := d.Column(table, column)
	if meta == nil || meta.Enum == nil {
		return nil, fmt.Errorf("%s.%s is an enum in proto but has no enum mapping in the domain layer (specs/<domain>/_domain.yaml)", table, column)
	}
	desc, err := files.FindDescriptorByName(protoreflect.FullName(meta.Enum.Proto))
	if err != nil {
		return nil, fmt.Errorf("domain enum %s.%s: proto %s: %w", table, column, meta.Enum.Proto, err)
	}
	ed, ok := desc.(protoreflect.EnumDescriptor)
	if !ok {
		return nil, fmt.Errorf("domain enum %s.%s: %s is not an enum", table, column, meta.Enum.Proto)
	}
	if string(ed.ParentFile().Package()) != protoPkg {
		return nil, fmt.Errorf("domain enum %s.%s: %s must be in package %s", table, column, meta.Enum.Proto, protoPkg)
	}
	goType := string(ed.Name())
	if p, ok := ed.Parent().(protoreflect.MessageDescriptor); ok {
		goType = string(p.Name()) + "_" + goType
	}
	col, ok := cat.column(table, column)
	if !ok {
		return nil, fmt.Errorf("domain enum %s.%s: column not in schema", table, column)
	}
	dbType, ok := dbIntGoType[col.Type]
	if !ok {
		return nil, fmt.Errorf("domain enum %s.%s: column type %s is not an integer type", table, column, col.Type)
	}
	m := &enumMapping{
		Table: table, Column: column, Helper: enumHelperName(table, column), DBGoType: dbType,
		GoType: pbAlias + "." + goType,
	}
	covered := map[string]bool{}
	for _, dbv := range meta.Enum.SortedDBValues() {
		name := meta.Enum.Values[dbv]
		v := ed.Values().ByName(protoreflect.Name(name))
		if v == nil {
			return nil, fmt.Errorf("domain enum %s.%s: %s is not a value of %s", table, column, name, meta.Enum.Proto)
		}
		if v.Number() == 0 {
			return nil, fmt.Errorf("domain enum %s.%s: %s is the zero value (reserved for UNSPECIFIED)", table, column, name)
		}
		if covered[name] {
			return nil, fmt.Errorf("domain enum %s.%s: %s is mapped from more than one DB value", table, column, name)
		}
		covered[name] = true
		m.Cases = append(m.Cases, enumCase{DB: dbv, Const: pbAlias + "." + goType + "_" + name})
	}
	for i := 0; i < ed.Values().Len(); i++ {
		v := ed.Values().Get(i)
		if v.Number() == 0 {
			m.Unspecified = pbAlias + "." + goType + "_" + string(v.Name())
			continue
		}
		if !covered[string(v.Name())] {
			return nil, fmt.Errorf("domain enum %s.%s: proto value %s has no DB value in the domain layer", table, column, v.Name())
		}
	}
	if m.Unspecified == "" {
		return nil, fmt.Errorf("proto enum %s has no zero value", meta.Enum.Proto)
	}
	return m, nil
}

// writeEnums: 每个 handler 包一个 enums_gen.go。
func writeEnums(svc service, mappings []*enumMapping, pbAlias, pbPath string) error {
	path := filepath.Join("internal/handler", svc.Domain, "enums_gen.go")
	if len(mappings) == 0 {
		_ = os.Remove(path)
		_ = os.Remove(filepath.Join("internal/handler", svc.Domain, "enums_gen_test.go"))
		return nil
	}
	sort.Slice(mappings, func(i, j int) bool { return mappings[i].Helper < mappings[j].Helper })
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by factory from the domain layer. DO NOT EDIT.\n\npackage %s\n\nimport (\n\t%s %q\n\t\"apifactory/platform/anomaly\"\n)\n", svc.Domain, pbAlias, pbPath)
	for _, m := range mappings {
		fmt.Fprintf(&b, "\n// %sToProto: %s.%s 的 DB 值 → proto。映射表以外的值 → UNSPECIFIED,并记录 data_anomaly_total。\nfunc %sToProto(v %s) %s {\n\tswitch v {\n", m.Helper, m.Table, m.Column, m.Helper, m.DBGoType, m.GoType)
		for _, c := range m.Cases {
			fmt.Fprintf(&b, "\tcase %d:\n\t\treturn %s\n", c.DB, c.Const)
		}
		fmt.Fprintf(&b, "\t}\n\tanomaly.Report(%q, %q, v)\n\treturn %s\n}\n", m.Table, m.Column, m.Unspecified)
		fmt.Fprintf(&b, "\n// %sToDB: proto → DB 值。UNSPECIFIED 和未定义的值被 protovalidate 拒绝,不会到这里;万一到了返回 -1(不匹配任何行)。\nfunc %sToDB(v %s) %s {\n\tswitch v {\n", m.Helper, m.Helper, m.GoType, m.DBGoType)
		for _, c := range m.Cases {
			fmt.Fprintf(&b, "\tcase %s:\n\t\treturn %d\n", c.Const, c.DB)
		}
		fmt.Fprintf(&b, "\t}\n\treturn -1\n}\n")
		fmt.Fprintf(&b, "\n// %sPtrToDB: 可选的筛选条件(nil = 不筛选)。\nfunc %sPtrToDB(p *%s) *%s {\n\tif p == nil {\n\t\treturn nil\n\t}\n\tv := %sToDB(*p)\n\treturn &v\n}\n", m.Helper, m.Helper, m.GoType, m.DBGoType, m.Helper)
	}
	if err := writeGo(path, []byte(b.String())); err != nil {
		return err
	}
	return writeEnumTests(svc, mappings, pbAlias, pbPath)
}

// writeEnumTests: 映射表的往返 + 未知值(DB 约束让它插不进测试 DB,所以在单元测试里验证)。
func writeEnumTests(svc service, mappings []*enumMapping, pbAlias, pbPath string) error {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by factory from the domain layer. DO NOT EDIT.\n\npackage %s\n\nimport (\n\t\"strings\"\n\t\"testing\"\n\n\t%s %q\n\t\"apifactory/platform/anomaly\"\n)\n", svc.Domain, pbAlias, pbPath)
	for _, m := range mappings {
		maxDB := int64(0)
		fmt.Fprintf(&b, "\nfunc Test_%s_RoundTrip(t *testing.T) {\n\tcases := []struct {\n\t\tdb %s\n\t\tpb %s\n\t}{\n", m.Helper, m.DBGoType, m.GoType)
		for _, c := range m.Cases {
			maxDB = max(maxDB, c.DB)
			fmt.Fprintf(&b, "\t\t{%d, %s},\n", c.DB, c.Const)
		}
		fmt.Fprintf(&b, "\t}\n\tfor _, c := range cases {\n\t\tif got := %sToProto(c.db); got != c.pb {\n\t\t\tt.Errorf(\"ToProto(%%d) = %%v, want %%v\", c.db, got, c.pb)\n\t\t}\n\t\tif got := %sToDB(c.pb); got != c.db {\n\t\t\tt.Errorf(\"ToDB(%%v) = %%d, want %%d\", c.pb, got, c.db)\n\t\t}\n\t}\n}\n", m.Helper, m.Helper)
		unknown := maxDB + 100
		fmt.Fprintf(&b, "\nfunc Test_%s_Unknown(t *testing.T) {\n\tif got := %sToProto(%d); got != %s {\n\t\tt.Fatalf(\"unknown DB value: got %%v, want UNSPECIFIED\", got)\n\t}\n\tvar w strings.Builder\n\tanomaly.WriteMetrics(&w)\n\tif !strings.Contains(w.String(), `data_anomaly_total{table=%q,column=%q}`) {\n\t\tt.Fatalf(\"anomaly not reported:\\n%%s\", w.String())\n\t}\n}\n", m.Helper, m.Helper, unknown, m.Unspecified, m.Table, m.Column)
	}
	return writeGo(filepath.Join("internal/handler", svc.Domain, "enums_gen_test.go"), []byte(b.String()))
}
