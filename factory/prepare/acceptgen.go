func fieldRules(fd protoreflect.FieldDescriptor) *validate.FieldRules {
	opts, ok := fd.Options().(*descriptorpb.FieldOptions)
	if !ok || opts == nil || !proto.HasExtension(opts, validate.E_Field) {
		return nil
	}
	r, _ := proto.GetExtension(opts, validate.E_Field).(*validate.FieldRules)
	return r
}

// baseRequest: 第一个 code: OK 的人写用例的请求(作为"其他字段都合法"的基础)。
func baseRequest(s *spec.Spec) (map[string]any, bool) {
	for _, c := range s.Acceptance.Cases {
		st := c.AllSteps()[0]
		if strings.EqualFold(st.Expect.Code, "OK") {
			out := map[string]any{}
			for k, v := range st.Request {
				if str, ok := v.(string); ok && strings.HasPrefix(str, "$") {
					continue
				}
				out[k] = v
			}
			return out, true
		}
	}
	return nil, false
}

type boundary struct {
	label string
	value any
	valid bool
	unset bool
}

func intBoundaries(gt, gte, lt, lte *int64, in []int64) []boundary {
	var b []boundary
	if gt != nil {
		b = append(b, boundary{fmt.Sprintf("= %d(gt %d 的边界,违反)", *gt, *gt), *gt, false, false},
			boundary{fmt.Sprintf("= %d(gt %d 的边界,合法)", *gt+1, *gt), *gt + 1, true, false})
	}
	if gte != nil {
		b = append(b, boundary{fmt.Sprintf("= %d(gte %d 的边界,违反)", *gte-1, *gte), *gte - 1, false, false},
			boundary{fmt.Sprintf("= %d(gte %d 的边界,合法)", *gte, *gte), *gte, true, false})
	}
	if lt != nil {
		b = append(b, boundary{fmt.Sprintf("= %d(lt %d 的边界,违反)", *lt, *lt), *lt, false, false},
			boundary{fmt.Sprintf("= %d(lt %d 的边界,合法)", *lt-1, *lt), *lt - 1, true, false})
	}
	if lte != nil {
		b = append(b, boundary{fmt.Sprintf("= %d(lte %d 的边界,违反)", *lte+1, *lte), *lte + 1, false, false},
			boundary{fmt.Sprintf("= %d(lte %d 的边界,合法)", *lte, *lte), *lte, true, false})
	}
	if len(in) > 0 {
		mx, mn := in[0], in[0]
		for _, v := range in {
			mx, mn = max(mx, v), min(mn, v)
		}
		b = append(b, boundary{fmt.Sprintf("= %d(不在 in %v 内)", mx+1, in), mx + 1, false, false},
			boundary{fmt.Sprintf("= %d(不在 in %v 内)", mn-1, in), mn - 1, false, false})
		for _, v := range in {
			b = append(b, boundary{fmt.Sprintf("= %d(in %v 内)", v, in), v, true, false})
		}
	}
	return b
}

func ptr[T any](v T) *T { return &v }

func boundariesFor(fd protoreflect.FieldDescriptor, r *validate.FieldRules) ([]boundary, []string) {
	var b []boundary
	var rules []string
	if r.GetRequired() {
		b = append(b, boundary{"未指定(required)", nil, false, true})
		rules = append(rules, "required")
	}
	switch {
	case r.HasInt32():
		x := r.GetInt32()
		var gt, gte, lt, lte *int64
		if x.HasGt() {
			gt = ptr(int64(x.GetGt()))
		}
		if x.HasGte() {
			gte = ptr(int64(x.GetGte()))
		}
		if x.HasLt() {
			lt = ptr(int64(x.GetLt()))
		}
		if x.HasLte() {
			lte = ptr(int64(x.GetLte()))
		}
		var in []int64
		for _, v := range x.GetIn() {
			in = append(in, int64(v))
		}
		b = append(b, intBoundaries(gt, gte, lt, lte, in)...)
		rules = append(rules, "int32 范围/in")
	case r.HasInt64():
		x := r.GetInt64()
		var gt, gte, lt, lte *int64
		if x.HasGt() {
			gt = ptr(x.GetGt())
		}
		if x.HasGte() {
			gte = ptr(x.GetGte())
		}
		if x.HasLt() {
			lt = ptr(x.GetLt())
		}
		if x.HasLte() {
			lte = ptr(x.GetLte())
		}
		b = append(b, intBoundaries(gt, gte, lt, lte, x.GetIn())...)
		rules = append(rules, "int64 范围/in")
	case r.HasString():
		x := r.GetString()
		if x.HasMinLen() && x.GetMinLen() > 0 {
			n := int(x.GetMinLen())
			b = append(b, boundary{fmt.Sprintf("长度 %d(min_len %d 的边界,违反)", n-1, n), strings.Repeat("a", n-1), false, false},
				boundary{fmt.Sprintf("长度 %d(min_len %d 的边界,合法)", n, n), strings.Repeat("a", n), true, false})
		}
		if x.HasMaxLen() {
			n := int(x.GetMaxLen())
			b = append(b, boundary{fmt.Sprintf("长度 %d(max_len %d 的边界,违反)", n+1, n), strings.Repeat("a", n+1), false, false},
				boundary{fmt.Sprintf("长度 %d(max_len %d 的边界,合法)", n, n), strings.Repeat("a", n), true, false})
		}
		rules = append(rules, "string 长度")
	}
	return b, rules
}

func validationSuite(s *spec.Spec, md protoreflect.MethodDescriptor) (spec.Suite, []string) {
	suite := spec.Suite{Name: "validation"}
	base, ok := baseRequest(s)
	if !ok {
		if s.PatternKind() == "list_keyset" {
			base = map[string]any{}
		} else {
			return suite, []string{"validation: 未生成(没有 code: OK 的人写用例可作为基础请求)"}
		}
	}
	var cov []string
	in := md.Input()
	for i := 0; i < in.Fields().Len(); i++ {
		fd := in.Fields().Get(i)
		r := fieldRules(fd)
		if r == nil {
			continue
		}
		bs, rules := boundariesFor(fd, r)
		if len(bs) == 0 {
			continue
		}
		cov = append(cov, fmt.Sprintf("validation: %s(%s)", fd.Name(), strings.Join(rules, ", ")))
		for _, b := range bs {
			req := map[string]any{}
			for k, v := range base {
				req[k] = v
			}
			if b.unset {
				delete(req, string(fd.Name()))
			} else {
				req[string(fd.Name())] = b.value
			}
			code := "INVALID_ARGUMENT"
			if b.valid {
				code = "!INVALID_ARGUMENT" // 合法输入: 可能是 OK 也可能是 NOT_FOUND,但不能被校验拒绝
			}
			suite.Cases = append(suite.Cases, spec.Case{
				Name:    fmt.Sprintf("%s %s", fd.Name(), b.label),
				Request: req,
				Expect:  spec.Expect{Code: code},
			})
		}
	}
	if in.Options() != nil {
		if opts, ok := in.Options().(*descriptorpb.MessageOptions); ok && proto.HasExtension(opts, validate.E_Message) {
			cov = append(cov, "validation: 消息级 CEL 规则不自动生成(需要人写用例)")
		}
	}
	return suite, cov
}

