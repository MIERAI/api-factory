// 自动生成验收用例(机制测试)。
//
// 循环论证的边界: 这里的期待值和生成的代码来自同一份声明,所以验证不了"声明是否符合业务意图"
// (那是人写的用例和审查的职责)。这里验证的是"工厂和平台有没有把声明正确地变成代码":
//   - validation: proto 的 buf.validate 规则 → 边界值(违反 → INVALID_ARGUMENT,刚好合法 → 不是 INVALID_ARGUMENT)
//   - get_by_id / list_keyset: 工厂自己合成 fixture,用独立的参考实现(内存里筛选/排序/分页)算期待值,
//     和"生成 SQL → sqlc → 映射 → 服务"这条真实路径做差分

