type synthPlan struct {
	eqValues map[string][]any // 列 → 轮流取的值(eq 筛选列)
	tieCol   string           // 制造并列值的列(keyset 的第一排序列)
}

func eqCandidates(f resolvedFilter) []any {
	if r := fieldRules(f.Field); r != nil {
		switch {
		case r.HasInt32() && len(r.GetInt32().GetIn()) > 0:
			var out []any
			for _, v := range r.GetInt32().GetIn() {
				out = append(out, int64(v))
			}
			return out
		case r.HasInt64() && len(r.GetInt64().GetIn()) > 0:
			var out []any
			for _, v := range r.GetInt64().GetIn() {
				out = append(out, v)
			}
			return out
		}
	}
	switch kindOf(f.Column.Type) {
	case "int":
		return []any{int64(1), int64(2), int64(3)}
	case "text":
		return []any{"alpha", "beta"}
	case "bool":
		return []any{true, false}
	}
	return nil
}

func kindOf(sqlType string) string {
	switch sqlType {
	case "int2", "int4", "int8", "smallint", "integer", "bigint", "serial", "bigserial":
		return "int"
	case "text", "varchar", "bpchar", "char":
		return "text"
	case "timestamptz", "timestamp":
		return "time"
	case "bool", "boolean":
		return "bool"
	}
	return ""
}

// synthesize: 为 table 合成 n 行。eq 筛选列轮流取候选值;tieCol 每两行取同一个值(制造并列);
// 其他 NOT NULL 列按类型取唯一值;可空且用不到的列为 NULL。
func synthesize(cat *catalog, table string, n int, plan synthPlan, needed map[string]bool) ([]map[string]any, error) {
	var rows []map[string]any
	for i := 0; i < n; i++ {
		row := map[string]any{}
		group := i // 并列组: tieCol 有值时每两行一组
		if plan.tieCol != "" {
			group = i / 2
		}
		for _, c := range cat.tables[table] {
			if vals, ok := plan.eqValues[c.Name]; ok {
				// 同一并列组共享筛选值: 筛选后的结果里也必须有并列行,否则"并列时的次级排序"测不到
				row[c.Name] = vals[group%len(vals)]
				continue
			}
			if !c.NotNull && !needed[c.Name] {
				continue
			}
			step := i
			if c.Name == plan.tieCol {
				step = i / 2
			}
			switch kindOf(c.Type) {
			case "int":
				row[c.Name] = int64(step + 1)
			case "text":
				row[c.Name] = fmt.Sprintf("v%02d", step+1)
			case "time":
				row[c.Name] = synthBase.Add(time.Duration(step) * time.Hour)
			case "bool":
				row[c.Name] = step%2 == 0
			default:
				return nil, fmt.Errorf("cannot synthesize column %s.%s of type %s", table, c.Name, c.Type)
			}
		}
		rows = append(rows, row)
	}
	return rows, nil
}

func fixtureRows(rows []map[string]any) []map[string]any {
	var out []map[string]any
	for _, r := range rows {
		m := map[string]any{}
		for k, v := range r {
			m[k] = jsonValue(v)
		}
		out = append(out, m)
	}
	return out
}

// jsonValue: fixture / 请求 / 期待值里的表示(时间 → RFC3339 UTC,与 protojson 一致)。
func jsonValue(v any) any {
	if t, ok := v.(time.Time); ok {
		return t.UTC().Format(time.RFC3339)
	}
	return v
}

func compare(a, b any) int {
	switch x := a.(type) {
	case int64:
		y := b.(int64)
		switch {
		case x < y:
			return -1
		case x > y:
			return 1
		}
		return 0
	case string:
		return strings.Compare(x, b.(string))
	case time.Time:
		return x.Compare(b.(time.Time))
	case bool:
		y := b.(bool)
		switch {
		case x == y:
			return 0
		case !x:
			return -1
		}
		return 1
	}
	panic(fmt.Sprintf("compare: unsupported %T", a))
}

func opHolds(op string, c int) bool {
	switch op {
	case "eq":
		return c == 0
	case "gt":
		return c > 0
	case "gte":
		return c >= 0
	case "lt":
		return c < 0
	case "lte":
		return c <= 0
	}
	return false
}

// oracleFilter: 参考实现。values 里没有的筛选条件视为未指定。
func oracleFilter(rows []map[string]any, filters []resolvedFilter, values map[string]any) []map[string]any {
	var out []map[string]any
	for _, r := range rows {
		ok := true
		for _, f := range filters {
			v, given := values[f.Name]
			if !given {
				continue
			}
			if !opHolds(f.Op, compare(r[f.Column.Name], v)) {
				ok = false
				break
			}
		}
		if ok {
			out = append(out, r)
		}
	}
	return out
}

func oracleSort(rows []map[string]any, orderBy []string, desc bool) []map[string]any {
	out := append([]map[string]any(nil), rows...)
	sort.SliceStable(out, func(i, j int) bool {
		for _, c := range orderBy {
			if d := compare(out[i][c], out[j][c]); d != 0 {
				if desc {
					return d > 0
				}
				return d < 0
			}
		}
		return false
	})
	return out
}

func items(rows []map[string]any, fields []string) []any {
	out := []any{}
	for _, r := range rows {
		m := map[string]any{}
		for _, f := range fields {
			if v, ok := r[f]; ok {
				m[f] = jsonValue(v)
			}
		}
		out = append(out, m)
	}
	return out
}

func messageFieldNames(m protoreflect.MessageDescriptor) []string {
	var out []string
	for i := 0; i < m.Fields().Len(); i++ {
		out = append(out, string(m.Fields().Get(i).Name()))
	}
	return out
}

