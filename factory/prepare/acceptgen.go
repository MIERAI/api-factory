func listKeysetSuite(s *spec.Spec, md protoreflect.MethodDescriptor, cat *catalog) (spec.Suite, []string, error) {
	suite := spec.Suite{Name: "pattern:list_keyset"}
	p := s.Pattern
	table := s.Datasource.Table
	desc := p.Direction == "desc"
	filters, err := resolveFilters(s, md, cat)
	if err != nil {
		return suite, nil, err
	}
	cols, err := selectColumns(s, md, cat)
	if err != nil {
		return suite, nil, err
	}
	needed := map[string]bool{}
	for _, c := range cols {
		needed[c] = true
	}
	plan := synthPlan{eqValues: map[string][]any{}, tieCol: p.OrderBy[0]}
	for _, f := range filters {
		if f.Op == "eq" {
			if c := eqCandidates(f); len(c) > 0 && f.Column.Name != plan.tieCol {
				plan.eqValues[f.Column.Name] = c
			}
		}
		needed[f.Column.Name] = true
	}
	rows, err := synthesize(cat, table, synthRows, plan, needed)
	if err != nil {
		return suite, nil, err
	}
	suite.Fixtures = map[string][]map[string]any{table: fixtureRows(rows)}

	var itemsField protoreflect.FieldDescriptor
	out := md.Output()
	for i := 0; i < out.Fields().Len(); i++ {
		if fd := out.Fields().Get(i); fd.IsList() && fd.Kind() == protoreflect.MessageKind {
			itemsField = fd
		}
	}
	itemName := string(itemsField.Name())
	itemFields := messageFieldNames(itemsField.Message())
	list := func(vals map[string]any) []map[string]any {
		return oracleSort(oracleFilter(rows, filters, vals), p.OrderBy, desc)
	}
	add := func(name string, req map[string]any, resp map[string]any) {
		suite.Cases = append(suite.Cases, spec.Case{Name: name, Request: req, Expect: spec.Expect{Code: "OK", Response: resp}})
	}
	tokenFor := func(more bool) any {
		if more {
			return "$nonempty"
		}
		return "$absent"
	}
	var cov []string

	// 无筛选: 全部,排序(含并列行的次序),字段映射
	all := list(nil)
	add("无筛选 — 排序与字段映射(含并列行)", map[string]any{},
		map[string]any{itemName: items(all, itemFields), "next_page_token": tokenFor(len(all) > int(p.PageSize.Default))})
	cov = append(cov, fmt.Sprintf("list_keyset: 排序 %v %s(合成数据含并列值)与字段映射", p.OrderBy, p.Direction))

	key := p.OrderBy[len(p.OrderBy)-1]

	// 每个筛选条件单独
	for _, f := range filters {
		var vals []any
		switch {
		case plan.eqValues[f.Column.Name] != nil:
			vals = plan.eqValues[f.Column.Name]
		default: // 范围条件: 取中间一行的值做边界
			vals = []any{all[len(all)/2][f.Column.Name]}
		}
		for _, v := range vals {
			got := list(map[string]any{f.Name: v})
			add(fmt.Sprintf("筛选 %s %s %v", f.Name, f.SQLOp, jsonValue(v)),
				map[string]any{f.Name: jsonValue(v)},
				map[string]any{itemName: items(got, []string{p.OrderBy[len(p.OrderBy)-1]})})
		}
		cov = append(cov, fmt.Sprintf("list_keyset: 筛选 %s → %s %s(presence=%v)", f.Name, f.Column.Name, f.SQLOp, f.Presence))
	}

	// 所有 eq 条件组合: 让执行计划从"按索引顺序扫描"变成"筛选后排序",暴露依赖物理顺序的排序 bug
	combo := map[string]any{}
	for _, f := range filters {
		if vals := plan.eqValues[f.Column.Name]; vals != nil {
			combo[f.Name] = vals[0]
		}
	}
	if len(combo) >= 2 {
		got := list(combo)
		req := map[string]any{}
		for k, v := range combo {
			req[k] = jsonValue(v)
		}
		add("所有 eq 条件组合(筛选后排序,并列行次序)", req, map[string]any{itemName: items(got, []string{key})})
		cov = append(cov, "list_keyset: eq 条件组合(不依赖索引顺序的排序)")
	}

	// 翻页走到底: k=1(并列行跨页)、k=3(最后一页不满)、k=n/2(最后一页刚好满)
	for _, k := range []int{1, 3, synthRows / 2} {
		var steps []spec.Step
		for start := 0; start < len(all); start += k {
			end := min(start+k, len(all))
			req := map[string]any{"page_size": k}
			if start > 0 {
				req["page_token"] = "$prev.next_page_token"
			}
			steps = append(steps, spec.Step{Request: req, Expect: spec.Expect{Code: "OK",
				Response: map[string]any{itemName: items(all[start:end], []string{key}), "next_page_token": tokenFor(end < len(all))}}})
		}
		suite.Cases = append(suite.Cases, spec.Case{Name: fmt.Sprintf("翻页走到底 page_size=%d", k), Steps: steps})
	}
	cov = append(cov, "list_keyset: 翻页(并列行跨页 / 最后一页不满 / 最后一页刚好满)")

	// 翻页途中改 page_size 是允许的
	if len(all) >= 5 {
		suite.Cases = append(suite.Cases, spec.Case{Name: "翻页途中改 page_size 是允许的", Steps: []spec.Step{
			{Request: map[string]any{"page_size": 2}, Expect: spec.Expect{Code: "OK", Response: map[string]any{itemName: items(all[:2], []string{key}), "next_page_token": "$nonempty"}}},
			{Request: map[string]any{"page_size": 3, "page_token": "$prev.next_page_token"}, Expect: spec.Expect{Code: "OK", Response: map[string]any{itemName: items(all[2:5], []string{key})}}},
		}})
	}
	// 翻页途中改筛选条件 → 旧 token 失效
	for _, f := range filters {
		if vals := plan.eqValues[f.Column.Name]; len(vals) >= 2 {
			suite.Cases = append(suite.Cases, spec.Case{Name: fmt.Sprintf("翻页途中改筛选条件(%s) → INVALID_ARGUMENT", f.Name), Steps: []spec.Step{
				{Request: map[string]any{f.Name: jsonValue(vals[0]), "page_size": 1}, Expect: spec.Expect{Code: "OK", Response: map[string]any{"next_page_token": "$nonempty"}}},
				{Request: map[string]any{f.Name: jsonValue(vals[1]), "page_size": 1, "page_token": "$prev.next_page_token"}, Expect: spec.Expect{Code: "INVALID_ARGUMENT"}},
			}})
			break
		}
	}
	suite.Cases = append(suite.Cases, spec.Case{Name: "非法 page_token → INVALID_ARGUMENT",
		Request: map[string]any{"page_token": "not-a-valid-token"}, Expect: spec.Expect{Code: "INVALID_ARGUMENT"}})
	cov = append(cov, "list_keyset: page_token(改 page_size 允许 / 改筛选条件失效 / 非法 token)")
	return suite, cov, nil
}
