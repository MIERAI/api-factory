const synthRows = 8

var synthBase = time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)

func writeAutoAcceptance(s *spec.Spec, md protoreflect.MethodDescriptor, cat *catalog) error {
	a := &spec.AutoAcceptance{Spec: s.Path}

	if suite, cov := validationSuite(s, md); len(suite.Cases) > 0 {
		a.Suites = append(a.Suites, suite)
		a.Coverage = append(a.Coverage, cov...)
	}
	if s.Datasource.SQL == "" { // 逃生口的 SQL 没有可推导的语义,不生成模式套件
		var suite spec.Suite
		var cov []string
		var err error
		switch s.PatternKind() {
		case "get_by_id":
			suite, cov, err = getByIDSuite(s, md, cat)
		case "list_keyset":
			suite, cov, err = listKeysetSuite(s, md, cat)
		}
		if err != nil {
			return fmt.Errorf("auto acceptance: %w", err)
		}
		if len(suite.Cases) > 0 {
			a.Suites = append(a.Suites, suite)
			a.Coverage = append(a.Coverage, cov...)
		}
	}

	path := spec.AutoAcceptancePath(s.ID())
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	b, err := yaml.Marshal(a)
	if err != nil {
		return err
	}
	header := "# Code generated by factory from " + s.Path + ". DO NOT EDIT.\n# 机制测试: 期待值来自声明本身,验证的是代码生成/平台,不是业务意图。\n"
	return os.WriteFile(path, append([]byte(header), b...), 0o644)
}

