package golang

// gen/db: 查询函数(取代 sqlc 的 Go 代码生成)。
//
// 统一的约定(没有 sqlc 的特例: 单参数直接传值 / 单列返回标量 / 列正好等于整张表时复用模型类型):
//
//	func (q *Queries) X(ctx context.Context, arg XParams) (XRow, error)     // :one
//	func (q *Queries) X(ctx context.Context, arg XParams) ([]XRow, error)   // :many
//
// 类型的来源:
//   - 声明式查询: 核心代数(IR 的 pipeline)。可空性由核心决定(sqlc 推断不了视图 / JSON 投影的可空性)
//   - 逃生口 SQL: sqlc 的分析结果(IR 的 query.columns / params)
//
// sqlc 仍然在编译器里做独立检查(SQL 能否解析、类型),但不再生成 Go 代码。

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"apifactory/factory/core"
	"apifactory/factory/ir"
)

const dbDir = "gen/db"

type goCol struct {
	Field string // Go 字段名
	Type  string // Go 类型
}

type goQuery struct {
	Name     string
	Const    string
	SQL      string
	Many     bool
	Params   []goCol
	Rows     []goCol
	usesTime bool
}

var kindGo = map[core.Kind]string{
	core.Int32: "int32", core.Int64: "int64", core.Text: "string", core.Bool: "bool",
	core.Decimal: "string", core.Date: "time.Time", core.Timestamp: "time.Time",
}

var sqlGo = map[string]string{
	"int2": "int16", "int4": "int32", "integer": "int32", "int8": "int64", "bigint": "int64",
	"text": "string", "varchar": "string", "bpchar": "string", "bool": "bool", "boolean": "bool",
	"float8": "float64", "float4": "float32", "timestamptz": "time.Time", "timestamp": "time.Time", "date": "time.Time",
}

func ptr(t string, nullable bool) string {
	if nullable {
		return "*" + t
	}
	return t
}

// goQueryOf: 一个 API 的查询 → Go 的描述。
func goQueryOf(api *ir.API) (*goQuery, error) {
	q := &goQuery{Name: api.Query.Name, Const: lowerFirst(api.Query.Name), Many: api.Query.Cardinality == "many"}
	if api.Pipeline != nil { // 声明式
		s, err := core.ToSQL(api.Pipeline, core.Options{})
		if err != nil {
			return nil, err
		}
		q.SQL = s.Text
		for _, d := range s.Params {
			t := kindGo[d.Type.Kind]
			if d.List {
				t = "[]" + t
			} else {
				t = ptr(t, !d.Required)
			}
			q.Params = append(q.Params, goCol{dbName(d.Name), t})
		}
		for _, c := range s.Columns {
			t, ok := kindGo[c.Type.Kind]
			if !ok {
				return nil, fmt.Errorf("%s: 列 %s 的类型 %s 不能作为输出", api.ID, c.Name, c.Type.Kind)
			}
			q.Rows = append(q.Rows, goCol{dbName(c.Name), ptr(t, c.Type.Nullable)})
		}
	} else {
		sql, err := positional(api.Query.SQL, api.Query.Params)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", api.ID, err)
		}
		q.SQL = sql
		for _, p := range api.Query.Params {
			t, ok := sqlGo[p.Type]
			if !ok {
				return nil, fmt.Errorf("%s: 参数 %s 的类型 %s 不支持", api.ID, p.Name, p.Type)
			}
			q.Params = append(q.Params, goCol{dbName(p.Name), ptr(t, !p.NotNull)})
		}
		for _, c := range api.Query.Columns {
			t, ok := sqlGo[c.Type]
			if !ok {
				return nil, fmt.Errorf("%s: 列 %s 的类型 %s 不支持(numeric 请在 SQL 里 ::text)", api.ID, c.Name, c.Type)
			}
			q.Rows = append(q.Rows, goCol{dbName(c.Name), ptr(t, !c.NotNull)})
		}
	}
	for _, c := range append(append([]goCol{}, q.Params...), q.Rows...) {
		q.usesTime = q.usesTime || strings.Contains(c.Type, "time.Time")
	}
	return q, nil
}

var reSqlcArg = regexp.MustCompile(`sqlc\.n?arg\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)`)

// positional: 逃生口 SQL 里的 sqlc.arg(x) / sqlc.narg(x) → $n。编号 = sqlc 分析给出的参数顺序(按首次出现)。
func positional(sql string, params []ir.Param) (string, error) {
	index := map[string]int{}
	for i, p := range params {
		index[p.Name] = i + 1
	}
	var bad []string
	out := reSqlcArg.ReplaceAllStringFunc(sql, func(m string) string {
		name := reSqlcArg.FindStringSubmatch(m)[1]
		i, ok := index[name]
		if !ok {
			bad = append(bad, name)
			return m
		}
		return fmt.Sprintf("$%d", i)
	})
	if len(bad) > 0 {
		return "", fmt.Errorf("SQL 的参数 %v 不在 sqlc 的分析结果里", bad)
	}
	return out, nil
}

const dbGo = `// Code generated by factory. DO NOT EDIT.

package db

import (
	"context"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
)

type DBTX interface {
	Exec(context.Context, string, ...interface{}) (pgconn.CommandTag, error)
	Query(context.Context, string, ...interface{}) (pgx.Rows, error)
	QueryRow(context.Context, string, ...interface{}) pgx.Row
}

func New(db DBTX) *Queries {
	return &Queries{db: db}
}

type Queries struct {
	db DBTX
}

func (q *Queries) WithTx(tx pgx.Tx) *Queries {
	return &Queries{db: tx}
}
`

// writeQueries: gen/db 全量重建。
func writeQueries(plan *ir.Plan) error {
	old, _ := filepath.Glob(filepath.Join(dbDir, "*.go"))
	for _, f := range old {
		_ = os.Remove(f)
	}
	if err := os.MkdirAll(dbDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dbDir, "db.go"), []byte(dbGo), 0o644); err != nil {
		return err
	}
	apis := make([]*ir.API, 0, len(plan.APIs))
	for i := range plan.APIs {
		if plan.APIs[i].Query.SQL != "" {
			apis = append(apis, &plan.APIs[i])
		}
	}
	sort.Slice(apis, func(i, j int) bool { return apis[i].ID < apis[j].ID })
	for _, api := range apis {
		q, err := goQueryOf(api)
		if err != nil {
			return err
		}
		src, err := renderQuery(api, q)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dbDir, api.ID+".sql.go"), src, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func renderQuery(api *ir.API, q *goQuery) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by factory from %s. DO NOT EDIT.\n\npackage db\n\nimport (\n\t\"context\"\n", api.SpecPath)
	if q.usesTime {
		b.WriteString("\t\"time\"\n")
	}
	b.WriteString(")\n\n")
	card := "one"
	if q.Many {
		card = "many"
	}
	fmt.Fprintf(&b, "const %s = `-- name: %s :%s\n%s\n`\n\n", q.Const, q.Name, card, strings.ReplaceAll(q.SQL, "`", "` + \"`\" + `"))
	fmt.Fprintf(&b, "type %sParams struct {\n", q.Name)
	for _, p := range q.Params {
		fmt.Fprintf(&b, "\t%s %s\n", p.Field, p.Type)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "type %sRow struct {\n", q.Name)
	for _, r := range q.Rows {
		fmt.Fprintf(&b, "\t%s %s\n", r.Field, r.Type)
	}
	b.WriteString("}\n\n")
	var args, scan []string
	for _, p := range q.Params {
		args = append(args, "arg."+p.Field)
	}
	for _, r := range q.Rows {
		scan = append(scan, "&i."+r.Field)
	}
	argList := ""
	if len(args) > 0 {
		argList = ", " + strings.Join(args, ", ")
	}
	if q.Many {
		fmt.Fprintf(&b, `func (q *Queries) %[1]s(ctx context.Context, arg %[1]sParams) ([]%[1]sRow, error) {
	rows, err := q.db.Query(ctx, %[2]s%[3]s)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var items []%[1]sRow
	for rows.Next() {
		var i %[1]sRow
		if err := rows.Scan(%[4]s); err != nil {
			return nil, err
		}
		items = append(items, i)
	}
	return items, rows.Err()
}
`, q.Name, q.Const, argList, strings.Join(scan, ", "))
	} else {
		fmt.Fprintf(&b, `func (q *Queries) %[1]s(ctx context.Context, arg %[1]sParams) (%[1]sRow, error) {
	row := q.db.QueryRow(ctx, %[2]s%[3]s)
	var i %[1]sRow
	err := row.Scan(%[4]s)
	return i, err
}
`, q.Name, q.Const, argList, strings.Join(scan, ", "))
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("%s: gofmt: %w\n%s", api.ID, err, b.String())
	}
	return src, nil
}

// dbName: 列名 / 参数名 → gen/db 的 Go 字段名。沿用 sqlc 的规则(handler 和 AI 写的逻辑依赖这些名字):
// 按 _ 切开,每段首字母大写,"id" 段写成 "ID"(customer_id → CustomerID)。
func dbName(s string) string {
	var b strings.Builder
	for _, seg := range strings.Split(s, "_") {
		if seg == "" {
			continue
		}
		if seg == "id" {
			b.WriteString("ID")
			continue
		}
		b.WriteString(strings.ToUpper(seg[:1]) + seg[1:])
	}
	return b.String()
}
