package golang

// 逻辑样例(spec.logic_examples)→ 单元测试。直接调用 compute 的逻辑函数,不经过 DB,
// 用于 DB 里造不出来的输入: 约束不允许的值(读到的未知 enum → UNSPECIFIED)、需要上万行才出现的边界。

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"apifactory/factory/ir"
)

func writeLogicExamples(g *genCtx) error {
	path := filepath.Join("internal/handler", g.svc.Domain, snake(g.api.Method)+"_logic_examples_gen_test.go")
	if len(g.api.Compute.Examples) == 0 {
		_ = os.Remove(path)
		return nil
	}
	row, _ := g.db.rowFields(g.query)
	t := &genCtx{api: g.api, svc: g.svc, query: g.query, db: g.db, pbAlias: g.pbAlias, enums: g.enums, imports: map[string]string{}}
	t.use("testing", "")
	segs := strings.Split(g.api.ProtoPackage, ".")
	t.use(modulePath+"/gen/"+strings.Join(segs, "/"), g.pbAlias)

	var b strings.Builder
	fmt.Fprintf(&b, "func Test_%s_Examples(t *testing.T) {\n", g.api.Compute.LogicFunction)
	for i, ex := range g.api.Compute.Examples {
		req, err := t.requestLiteral(ex.Request)
		if err != nil {
			return fmt.Errorf("logic_examples[%d]: %w", i, err)
		}
		fmt.Fprintf(&b, "\tt.Run(%q, func(t *testing.T) {\n\t\treq := %s\n\t\tvar rows []%s\n", ex.Name, req, g.logicRowType())
		for j, r := range ex.Rows {
			lit, count, err := t.rowLiteral(r, row)
			if err != nil {
				return fmt.Errorf("logic_examples[%d].rows[%d]: %w", i, j, err)
			}
			fmt.Fprintf(&b, "\t\tfor i := 0; i < %d; i++ {\n\t\t\trows = append(rows, %s)\n\t\t}\n", count, lit)
		}
		fmt.Fprintf(&b, "\t\tres, err := %s(req, rows)\n\t\tif err != nil {\n\t\t\tt.Fatalf(\"unexpected error: %%v\", err)\n\t\t}\n", g.api.Compute.LogicFunction)
		keys := make([]string, 0, len(ex.Expect))
		for k := range ex.Expect {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			check, err := t.expectCheck(k, ex.Expect[k])
			if err != nil {
				return fmt.Errorf("logic_examples[%d].expect.%s: %w", i, k, err)
			}
			b.WriteString(check)
		}
		b.WriteString("\t})\n")
	}
	b.WriteString("}\n")
	if t.imports["time"] != "" || strings.Contains(b.String(), "mustTime(") {
		b.WriteString("\nfunc mustTime(s string) time.Time {\n\tif v, err := time.Parse(time.DateOnly, s); err == nil { // 日期 YYYY-MM-DD\n\t\treturn v\n\t}\n\tv, err := time.Parse(time.RFC3339Nano, s)\n\tif err != nil {\n\t\tpanic(err)\n\t}\n\treturn v\n}\n\nfunc ptrOf[T any](v T) *T { return &v }\n")
		t.use("time", "")
	}
	src := t.header(b.String())
	src = strings.Replace(src, "// Code generated by factory from "+g.api.SpecPath+". DO NOT EDIT.\n// pattern: compute\n",
		"// Code generated by factory from "+g.api.SpecPath+" (logic_examples). DO NOT EDIT.\n", 1)
	return writeGo(path, []byte(src))
}

func (t *genCtx) requestLiteral(req map[string]any) (string, error) {
	in := &t.api.Request
	var fields []string
	keys := make([]string, 0, len(req))
	for k := range req {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fd := in.Field(k)
		if fd == nil {
			return "", fmt.Errorf("request: %s is not a field of %s", k, in.Name)
		}
		lit, err := t.protoLiteral(fd, req[k])
		if err != nil {
			return "", err
		}
		fields = append(fields, fmt.Sprintf("%s: %s,", goCamelCase(k), lit))
	}
	return fmt.Sprintf("&%s{\n%s\n}", t.pbType(in), strings.Join(fields, "\n")), nil
}

// enumShortName: factory.jobs.v1.JobStatus → JobStatus
func enumShortName(full string) string { return full[strings.LastIndex(full, ".")+1:] }

func (t *genCtx) protoLiteral(fd *ir.Field, v any) (string, error) {
	var lit string
	switch {
	case fd.Kind == "timestamp":
		t.use("google.golang.org/protobuf/types/known/timestamppb", "")
		return fmt.Sprintf("timestamppb.New(mustTime(%q))", fmt.Sprint(v)), nil
	case fd.Kind == "enum":
		lit = t.pbAlias + "." + enumShortName(fd.Enum) + "_" + fmt.Sprint(v)
	case fd.Kind == "string":
		lit = fmt.Sprintf("%q", fmt.Sprint(v))
	case fd.Kind == "bool", fd.Kind == "double", fd.Kind == "float":
		lit = fmt.Sprint(v)
	default:
		lit = fmt.Sprint(v) // 整数
	}
	if fd.Optional {
		k, _ := goKind(fd)
		if fd.Kind == "enum" {
			k = t.pbAlias + "." + enumShortName(fd.Enum)
		}
		return fmt.Sprintf("ptrOf[%s](%s)", k, lit), nil
	}
	return lit, nil
}

func (t *genCtx) rowLiteral(r map[string]any, row []goField) (string, int, error) {
	count := 1
	var fields []string
	keys := make([]string, 0, len(r))
	for k := range r {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		v := r[k]
		if k == "count" {
			n, ok := v.(int)
			if !ok || n < 1 {
				return "", 0, fmt.Errorf("count must be a positive integer")
			}
			count = n
			continue
		}
		f, ok := fieldByNorm(row, k)
		if !ok {
			return "", 0, fmt.Errorf("%s is not a column of the logic input row", k)
		}
		if v == nil {
			continue // NULL
		}
		var lit string
		switch {
		case t.enums[k] != nil:
			lit = t.enums[k].GoType + "_" + fmt.Sprint(v)
		case f.Type == "time.Time":
			lit = fmt.Sprintf("mustTime(%q)", timeString(v))
		case f.Type == "*time.Time":
			lit = fmt.Sprintf("ptrOf(mustTime(%q))", timeString(v))
		case f.Type == "string":
			lit = fmt.Sprintf("%q", fmt.Sprint(v))
		case f.Type == "*string": // 可空的文本 / 十进制(十进制在 Go 里是字符串)
			lit = fmt.Sprintf("ptrOf(%q)", fmt.Sprint(v))
		default:
			lit = fmt.Sprintf("%s(%v)", strings.TrimPrefix(f.Type, "*"), v)
			if strings.HasPrefix(f.Type, "*") {
				lit = "ptrOf(" + lit + ")"
			}
		}
		fields = append(fields, fmt.Sprintf("%s: %s,", f.Name, lit))
	}
	return fmt.Sprintf("%s{\n%s\n}", t.logicRowType(), strings.Join(fields, "\n")), count, nil
}

func timeString(v any) string {
	if tm, ok := v.(time.Time); ok {
		return tm.UTC().Format(time.RFC3339Nano)
	}
	return fmt.Sprint(v)
}

func (t *genCtx) expectCheck(field string, want any) (string, error) {
	out := &t.api.Response
	fd := out.Field(field)
	if fd == nil {
		return "", fmt.Errorf("%s is not a field of %s", field, out.Name)
	}
	goName := goCamelCase(field)
	presence := fd.Presence && !fd.List
	if fd.List { // 列表(多为行的列表): protojson 子集匹配
		b, err := json.Marshal(want)
		if err != nil {
			return "", err
		}
		t.use("apifactory/platform/testkit", "")
		return fmt.Sprintf("\t\ttestkit.MatchField(t, res, %q, %s)\n", field, "`"+string(b)+"`"), nil
	}
	if s, ok := want.(string); ok && s == "$absent" {
		if !presence {
			return "", fmt.Errorf("$absent needs a field with presence (optional)")
		}
		return fmt.Sprintf("\t\tif res.%s != nil {\n\t\t\tt.Errorf(\"%s: want unset, got %%v\", *res.%s)\n\t\t}\n", goName, field, goName), nil
	}
	lit, err := t.protoLiteral(fd, want)
	if err != nil {
		return "", err
	}
	if presence {
		lit = strings.TrimSuffix(strings.SplitN(lit, "](", 2)[len(strings.SplitN(lit, "](", 2))-1], ")")
		return fmt.Sprintf("\t\tif res.%s == nil {\n\t\t\tt.Errorf(\"%s: want %%v, got unset\", %s)\n\t\t} else if *res.%s != %s {\n\t\t\tt.Errorf(\"%s: want %%v, got %%v\", %s, *res.%s)\n\t\t}\n",
			goName, field, lit, goName, lit, field, lit, goName), nil
	}
	return fmt.Sprintf("\t\tif got := res.Get%s(); got != %s {\n\t\t\tt.Errorf(\"%s: want %%v, got %%v\", %s, got)\n\t\t}\n", goName, lit, field, lit), nil
}
