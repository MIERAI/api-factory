// Package mutant: 变异测试的"变异体合编"(mutant schemata)。
//
// margin 以前每个变异编译一个服务器(go build -overlay,201 个变异 = 201 次编译 + 链接)。
// 变异都是对生成的代码的一处文本替换,改的几乎都是一个顶层声明(SQL 的常量 / 一个函数)。
// 这里把所有变异编进同一个二进制,运行时用环境变量 FACTORY_MUTANT=<id> 选择:
//
//   - 常量(const q = `…`,SQL)→ var q = func() string { switch 选择 { case id: return 变异的值 }; return 原值 }()
//   - 函数 / 方法 → 变异后的函数体改名为 名字_zzMut<id> 放在文件末尾;原函数开头加
//     if zzMutantOn("<id>") { return 名字_zzMut<id>(参数…) }
//
// 不设 FACTORY_MUTANT = 和原来的代码完全一样。别的形状的变异(改了两个声明、改了 import、
// 参数没有名字、泛型 …)不合编,margin 照旧给它单独编译(Fallback 里写原因)。
// 等价性: 合编和单独编译的判定逐个比较过(PR 说明;scripts/mutate-par.py 的 SCHEMATA=0 是单独编译)。
package mutant

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Mutant: 一个变异。Path 是相对 Root 的原文件,Mutated 是变异后的文件内容。
type Mutant struct {
	ID      string `json:"id"`
	Path    string `json:"path"`
	Mutated string `json:"mutated"` // 变异后的文件(路径)
}

// Result: 合编的结果。Overlay 是 go build -overlay 的 JSON;Schemata = 合编了的变异;Fallback = 不合编的(原因)。
type Result struct {
	Overlay  string            `json:"overlay"`
	Schemata []string          `json:"schemata"`
	Fallback map[string]string `json:"fallback"`
}

const (
	envName  = "FACTORY_MUTANT"
	selVar   = "zzMutantSel"
	onFunc   = "zzMutantOn"
	suffix   = "_zzMut"
	helperGo = "zz_mutant_schemata_gen.go"
)

type decl struct {
	key        string // 种类 + 名字(两边的声明按顺序一一对应)
	start, end int    // 字节偏移
	node       ast.Decl
}

func parse(name string, src []byte) (*token.FileSet, *ast.File, []decl, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, name, src, parser.ParseComments)
	if err != nil {
		return nil, nil, nil, err
	}
	var ds []decl
	for _, d := range f.Decls {
		k := ""
		switch x := d.(type) {
		case *ast.FuncDecl:
			k = "func " + recvType(x) + "." + x.Name.Name
		case *ast.GenDecl:
			k = x.Tok.String()
			for _, s := range x.Specs {
				switch sp := s.(type) {
				case *ast.ValueSpec:
					for _, n := range sp.Names {
						k += " " + n.Name
					}
				case *ast.TypeSpec:
					k += " " + sp.Name.Name
				case *ast.ImportSpec:
					k += " " + sp.Path.Value
				}
			}
		}
		ds = append(ds, decl{key: k, start: fset.Position(d.Pos()).Offset, end: fset.Position(d.End()).Offset, node: d})
	}
	return fset, f, ds, nil
}

func recvType(f *ast.FuncDecl) string {
	if f.Recv == nil || len(f.Recv.List) == 0 {
		return ""
	}
	var b bytes.Buffer
	t := f.Recv.List[0].Type
	if s, ok := t.(*ast.StarExpr); ok {
		b.WriteString("*")
		t = s.X
	}
	if id, ok := t.(*ast.Ident); ok {
		b.WriteString(id.Name)
	} else {
		b.WriteString("?")
	}
	return b.String()
}

// skeleton: 去掉所有声明之后剩下的文本(包名、注释、空白)。两边必须一样。
func skeleton(src []byte, ds []decl) string {
	var b strings.Builder
	at := 0
	for _, d := range ds {
		b.Write(src[at:d.start])
		b.WriteString("\x00")
		at = d.end
	}
	b.Write(src[at:])
	return b.String()
}

// fileEdit: 一个原文件上的改动(多个变异)。
type fileEdit struct {
	pkg     string
	src     []byte
	fset    *token.FileSet
	decls   []decl
	consts  map[int][]constAlt // 声明的下标 → 各变异的值
	funcs   map[int][]funcAlt
	appends []string // 文件末尾追加的(改名后的变异函数)
}

type constAlt struct{ id, value string }
type funcAlt struct{ id, call string }

// Build: 生成合编的 overlay(写在 out 目录下)。root = 仓库根目录(绝对路径)。
func Build(root, out string, muts []Mutant) (*Result, error) {
	res := &Result{Fallback: map[string]string{}}
	edits := map[string]*fileEdit{}
	var order []string
	for _, m := range muts {
		e := edits[m.Path]
		if e == nil {
			src, err := os.ReadFile(filepath.Join(root, m.Path))
			if err != nil {
				return nil, err
			}
			fset, f, ds, err := parse(m.Path, src)
			if err != nil {
				return nil, err
			}
			e = &fileEdit{pkg: f.Name.Name, src: src, fset: fset, decls: ds, consts: map[int][]constAlt{}, funcs: map[int][]funcAlt{}}
			edits[m.Path] = e
			order = append(order, m.Path)
		}
		if why := e.add(m); why != "" {
			res.Fallback[m.ID] = why
			continue
		}
		res.Schemata = append(res.Schemata, m.ID)
	}
	replace := map[string]string{}
	pkgs := map[string]string{} // 目录 → 包名
	for i, p := range order {
		e := edits[p]
		if len(e.consts) == 0 && len(e.funcs) == 0 {
			continue
		}
		mf := filepath.Join(out, fmt.Sprintf("%d-%s", i, filepath.Base(p)))
		if err := os.WriteFile(mf, e.render(), 0o644); err != nil {
			return nil, err
		}
		replace[filepath.Join(root, p)] = mf
		pkgs[filepath.Dir(p)] = e.pkg
	}
	for dir, pkg := range pkgs { // 每个包一个: 读 FACTORY_MUTANT
		h := filepath.Join(out, strings.ReplaceAll(dir, "/", "_")+"-"+helperGo)
		src := fmt.Sprintf("// Code generated by factory/mutant (margin 的变异体合编). DO NOT EDIT.\n\npackage %s\n\nimport \"os\"\n\nvar %s = os.Getenv(%q)\n\nfunc %s(id string) bool { return %s == id }\n",
			pkg, selVar, envName, onFunc, selVar)
		if err := os.WriteFile(h, []byte(src), 0o644); err != nil {
			return nil, err
		}
		replace[filepath.Join(root, dir, helperGo)] = h
	}
	var b bytes.Buffer
	b.WriteString(`{"Replace":{`)
	keys := make([]string, 0, len(replace))
	for k := range replace {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for i, k := range keys {
		if i > 0 {
			b.WriteString(",")
		}
		fmt.Fprintf(&b, "%q:%q", k, replace[k])
	}
	b.WriteString("}}")
	res.Overlay = filepath.Join(out, "schemata-overlay.json")
	return res, os.WriteFile(res.Overlay, b.Bytes(), 0o644)
}

// add: 把一个变异加进这个文件的改动。返回不合编的原因(空 = 合编)。
func (e *fileEdit) add(m Mutant) string {
	msrc, err := os.ReadFile(m.Mutated)
	if err != nil {
		return err.Error()
	}
	_, _, mds, err := parse(m.Path, msrc)
	if err != nil {
		return "变异后的文件解析不了: " + err.Error()
	}
	if len(mds) != len(e.decls) {
		return "声明的个数变了"
	}
	if skeleton(e.src, e.decls) != skeleton(msrc, mds) {
		return "声明之外的部分(import / 注释)变了"
	}
	idx := -1
	for i := range mds {
		if mds[i].key != e.decls[i].key {
			return "声明的名字 / 顺序变了"
		}
		if !bytes.Equal(msrc[mds[i].start:mds[i].end], e.src[e.decls[i].start:e.decls[i].end]) {
			if idx >= 0 {
				return "改了不止一个声明"
			}
			idx = i
		}
	}
	if idx < 0 {
		return "没有改动"
	}
	switch o := e.decls[idx].node.(type) {
	case *ast.GenDecl:
		mg := mds[idx].node.(*ast.GenDecl)
		if o.Tok != token.CONST || o.Lparen.IsValid() || len(o.Specs) != 1 {
			return "改的是 const 以外的声明(或 const 块)"
		}
		os_, ms := o.Specs[0].(*ast.ValueSpec), mg.Specs[0].(*ast.ValueSpec)
		if len(os_.Names) != 1 || len(os_.Values) != 1 || len(ms.Values) != 1 || os_.Type != nil {
			return "const 不是 名字 = 值 的形状"
		}
		if _, ok := os_.Values[0].(*ast.BasicLit); !ok {
			return "const 的值不是字面量"
		}
		v := ms.Values[0] // 位置的差 = 字节偏移的差(一个文件)
		text := msrc[mds[idx].start:mds[idx].end]
		e.consts[idx] = append(e.consts[idx], constAlt{m.ID, string(text[v.Pos()-mg.Pos() : v.End()-mg.Pos()])})
		return ""
	case *ast.FuncDecl:
		mf := mds[idx].node.(*ast.FuncDecl)
		if o.Body == nil || o.Type.TypeParams != nil {
			return "函数没有函数体 / 是泛型"
		}
		call, why := dispatchCall(o, m.ID)
		if why != "" {
			return why
		}
		// 变异后的函数: 名字改成 名字_zzMut<id>
		d := mds[idx]
		text := string(msrc[d.start:d.end])
		nameOff := int(mf.Name.Pos() - mf.Pos())
		text = text[:nameOff] + mf.Name.Name + suffix + m.ID + text[nameOff+len(mf.Name.Name):]
		e.appends = append(e.appends, text)
		e.funcs[idx] = append(e.funcs[idx], funcAlt{m.ID, call})
		return ""
	}
	return "改的是不支持的声明"
}

// dispatchCall: 原函数开头加的分派语句。
func dispatchCall(f *ast.FuncDecl, id string) (string, string) {
	var args []string
	variadic := false
	for _, fld := range f.Type.Params.List {
		if len(fld.Names) == 0 {
			return "", "参数没有名字"
		}
		for _, n := range fld.Names {
			if n.Name == "_" {
				return "", "参数名是 _"
			}
			args = append(args, n.Name)
		}
		if _, ok := fld.Type.(*ast.Ellipsis); ok {
			variadic = true
		}
	}
	callee := f.Name.Name + suffix + id
	if f.Recv != nil {
		if len(f.Recv.List) != 1 || len(f.Recv.List[0].Names) != 1 || f.Recv.List[0].Names[0].Name == "_" {
			return "", "接收者没有名字"
		}
		callee = f.Recv.List[0].Names[0].Name + "." + callee
	}
	a := strings.Join(args, ", ")
	if variadic {
		a += "..."
	}
	if f.Type.Results == nil || len(f.Type.Results.List) == 0 {
		return fmt.Sprintf("if %s(%q) {\n\t\t%s(%s)\n\t\treturn\n\t}\n\t", onFunc, id, callee, a), ""
	}
	return fmt.Sprintf("if %s(%q) {\n\t\treturn %s(%s)\n\t}\n\t", onFunc, id, callee, a), ""
}

// render: 原文件 + 改动。
func (e *fileEdit) render() []byte {
	var b bytes.Buffer
	at := 0
	for i, d := range e.decls {
		if alts, ok := e.consts[i]; ok {
			g := d.node.(*ast.GenDecl)
			vs := g.Specs[0].(*ast.ValueSpec)
			b.Write(e.src[at:d.start])
			orig := string(e.src[e.fset.Position(vs.Values[0].Pos()).Offset:e.fset.Position(vs.Values[0].End()).Offset])
			fmt.Fprintf(&b, "var %s = func() string {\n\tswitch %s {\n", vs.Names[0].Name, selVar)
			for _, a := range alts {
				fmt.Fprintf(&b, "\tcase %q:\n\t\treturn %s\n", a.id, a.value)
			}
			fmt.Fprintf(&b, "\t}\n\treturn %s\n}()", orig)
			at = d.end
			continue
		}
		if alts, ok := e.funcs[i]; ok {
			f := d.node.(*ast.FuncDecl)
			lb := e.fset.Position(f.Body.Lbrace).Offset + 1
			b.Write(e.src[at:lb])
			b.WriteString("\n\t")
			for _, a := range alts {
				b.WriteString(a.call)
			}
			at = lb
		}
	}
	b.Write(e.src[at:])
	for _, t := range e.appends {
		b.WriteString("\n\n")
		b.WriteString(t)
		b.WriteString("\n")
	}
	return b.Bytes()
}
