package core

// 元件认证: 分桶的生产线(bucket.go,docs/design/hotspots.md §4)。参考 = 一行的语义:
//   取 x: 合计 ≥ x 才扣(否则不变,0 行);还 x: 合计 + x;写进表的 Q = 合计设成这个值;删除;TRUNCATE。
// 顺序执行: 每一步之后视图的 Q / 按桶记的列 = 参考;桶都 ≥ 0。
// 并发: 32 个连接同时取同一个键(量 1 / 2 / 3 混在一起)+ 同时还: 成功的合计 = 扣掉的量,最后的合计 = 参考,
// 不超卖(合计 ≥ 0,每个桶 ≥ 0),没有"假的不够"(失败的请求发生时,合计确实不够它的量: 用每个请求返回的行判断),没有死锁。

import (
	"context"
	"fmt"
	"math/rand"
	"os"
	"sync"
	"sync/atomic"
	"testing"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

func TestCertificationBucket(t *testing.T) {
	url := os.Getenv("FACTORY_TEST_DB")
	if url == "" {
		t.Skip("FACTORY_TEST_DB 没有设置(元件认证需要 Postgres)")
	}
	ctx := context.Background()
	conn, err := pgx.Connect(ctx, url)
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close(ctx)
	schema := fmt.Sprintf("core_cert_bucket_%d", os.Getpid())
	exec := func(q string, args ...any) {
		t.Helper()
		if _, err := conn.Exec(ctx, q, args...); err != nil {
			t.Fatalf("%v\n%s", err, q)
		}
	}
	for _, q := range []string{"DROP SCHEMA IF EXISTS " + schema + " CASCADE", "CREATE SCHEMA " + schema, "SET search_path = " + schema,
		`CREATE TABLE stock (sku text PRIMARY KEY, qty int4 NOT NULL CHECK (qty >= 0), note text, touched timestamptz)`,
		`CREATE TABLE orders (id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku text NOT NULL REFERENCES stock (sku))`,
	} {
		exec(q)
	}
	defer conn.Exec(ctx, "DROP SCHEMA "+schema+" CASCADE")
	// 先有数据(回填)
	exec(`INSERT INTO stock VALUES ('a', 37, 'x', '2026-01-01'), ('b', 0, NULL, NULL)`)
	spec := BucketSpec{Table: "stock", Column: "qty", Type: "int4", Key: []string{"sku"}, View: "hot_stock", BucketTable: "bucket_stock", N: 8,
		PerBucket: []string{"touched"}, Cols: []BucketCol{{"sku", "text"}, {"qty", "int4"}, {"note", "text"}, {"touched", "timestamptz"}}}
	ddl := BucketDDL(spec)
	exec(ddl)
	exec(ddl) // 幂等(迁移重放)

	ref := map[string]int64{"a": 37, "b": 0}
	n := 0
	check := func(name string) {
		t.Helper()
		n++
		rows, err := conn.Query(ctx, `SELECT sku, qty FROM hot_stock`)
		if err != nil {
			t.Fatal(err)
		}
		got := map[string]int64{}
		for rows.Next() {
			var k string
			var q int64
			_ = rows.Scan(&k, &q)
			got[k] = q
		}
		rows.Close()
		if fmt.Sprint(got) != fmt.Sprint(ref) {
			t.Errorf("%s: 视图 %v ≠ 参考 %v", name, got, ref)
		}
		var neg, base int
		_ = conn.QueryRow(ctx, `SELECT count(*) FILTER (WHERE qty < 0) FROM bucket_stock`).Scan(&neg)
		_ = conn.QueryRow(ctx, `SELECT count(*) FILTER (WHERE qty <> 0) FROM stock`).Scan(&base)
		if neg > 0 || base > 0 {
			t.Errorf("%s: 负的桶 %d 个 / 表本身的数量不是 0 的行 %d 个", name, neg, base)
		}
	}
	check("回填")
	take := func(c interface {
		QueryRow(context.Context, string, ...any) pgx.Row
	}, sku string, x int64) (int64, bool, error) {
		var after int64
		err := c.QueryRow(ctx, `UPDATE hot_stock SET qty = qty - $1, touched = now() WHERE sku = $2 AND qty >= $1 RETURNING qty`, x, sku).Scan(&after)
		if err == pgx.ErrNoRows {
			return 0, false, nil
		}
		return after, err == nil, err
	}
	rnd := rand.New(rand.NewSource(1))
	// 1. 顺序: 取(够 / 不够 / 正好)、还、写进表 = 设合计、其他列
	for i := 0; i < 120; i++ {
		sku := []string{"a", "b"}[rnd.Intn(2)]
		switch rnd.Intn(5) {
		case 0, 1, 2:
			x := int64(1 + rnd.Intn(9))
			after, ok, err := take(conn, sku, x)
			if err != nil {
				t.Fatal(err)
			}
			want := ref[sku] >= x
			if ok != want {
				t.Errorf("取 %s %d(合计 %d): 成功 = %v,应该 %v", sku, x, ref[sku], ok, want)
			}
			if ok {
				ref[sku] -= x
				if after != ref[sku] {
					t.Errorf("取之后返回的合计 %d ≠ %d", after, ref[sku])
				}
			}
		case 3:
			x := int64(1 + rnd.Intn(20))
			exec(`UPDATE hot_stock SET qty = qty + $1 WHERE sku = $2`, x, sku)
			ref[sku] += x
		case 4:
			v := int64(rnd.Intn(30))
			exec(`UPDATE stock SET qty = $1 WHERE sku = $2`, v, sku) // 直接写表 = 合计设成这个值(⚖️ H9)
			ref[sku] = v
		}
		check(fmt.Sprintf("顺序 %d", i))
	}
	exec(`UPDATE hot_stock SET note = 'y' WHERE sku = 'a'`) // 其他列: 冷路径
	var note string
	_ = conn.QueryRow(ctx, `SELECT note FROM hot_stock WHERE sku = 'a'`).Scan(&note)
	if note != "y" {
		t.Errorf("其他列: %q", note)
	}
	check("其他列")
	// 按桶记的列: 视图 = 最新设的
	exec(`UPDATE hot_stock SET qty = qty + 1, touched = '2030-01-01' WHERE sku = 'a'`)
	ref["a"]++
	var touched string
	_ = conn.QueryRow(ctx, `SELECT touched::date::text FROM hot_stock WHERE sku = 'a'`).Scan(&touched)
	if touched != "2030-01-01" {
		t.Errorf("按桶记的列: %s", touched)
	}
	exec(`INSERT INTO stock VALUES ('c', 5, NULL, NULL)`)
	ref["c"] = 5
	check("新建")
	exec(`DELETE FROM hot_stock WHERE sku = 'c'`)
	delete(ref, "c")
	check("删除(视图)")
	var orphan int
	_ = conn.QueryRow(ctx, `SELECT count(*) FROM bucket_stock WHERE sku = 'c'`).Scan(&orphan)
	if orphan > 0 {
		t.Errorf("删除之后还有桶 %d 个", orphan)
	}
	if _, err := conn.Exec(ctx, `UPDATE stock SET qty = -1 WHERE sku = 'a'`); err == nil {
		t.Error("合计设成负数: 应该被拒绝(桶的 CHECK)")
	}

	// 2. 并发: 32 个连接同时取 / 还同一个键
	cfg, err := pgxpool.ParseConfig(url)
	if err != nil {
		t.Fatal(err)
	}
	cfg.ConnConfig.RuntimeParams["search_path"] = schema
	cfg.MaxConns = 32
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatal(err)
	}
	defer pool.Close()
	for round := 0; round < 4; round++ {
		start := int64(40 + round*7)
		exec(`UPDATE stock SET qty = $1 WHERE sku = 'a'`, start)
		var taken, given, fails atomic.Int64
		var wg sync.WaitGroup
		errs := make(chan error, 64)
		for w := 0; w < 32; w++ {
			wg.Add(1)
			go func(w int) {
				defer wg.Done()
				r := rand.New(rand.NewSource(int64(round*100 + w)))
				for i := 0; i < 4; i++ {
					if round%2 == 1 && w%8 == 7 { // 还(奇数轮)
						x := int64(1 + r.Intn(3))
						if _, err := pool.Exec(ctx, `UPDATE hot_stock SET qty = qty + $1 WHERE sku = 'a'`, x); err != nil {
							errs <- err
							return
						}
						given.Add(x)
						continue
					}
					x := int64(1 + r.Intn(3))
					tx, err := pool.Begin(ctx)
					if err != nil {
						errs <- err
						return
					}
					_, ok, err := take(tx, "a", x)
					if err == nil && ok { // 同一个事务里还写别的表(外键 → 表的这一行的 KEY SHARE 锁)
						_, err = tx.Exec(ctx, `INSERT INTO orders (sku) VALUES ('a')`)
					}
					if err != nil {
						_ = tx.Rollback(ctx)
						errs <- err
						return
					}
					if err := tx.Commit(ctx); err != nil {
						errs <- err
						return
					}
					if ok {
						taken.Add(x)
					} else {
						fails.Add(1)
					}
				}
			}(w)
		}
		wg.Wait()
		close(errs)
		for err := range errs {
			t.Fatalf("并发 %d: %v(死锁 / 序列化失败也不应该有)", round, err)
		}
		ref["a"] = start - taken.Load() + given.Load()
		check(fmt.Sprintf("并发 %d(取 %d / 还 %d / 不够 %d 次)", round, taken.Load(), given.Load(), fails.Load()))
		// 没有"假的不够": 不够的请求只能在合计真的不够(< 3)之后出现 —— 最后剩下的合计 < 失败的请求里最小的量 不一定成立,
		// 但如果有失败,结束时(没有人再取)合计一定 < 3(否则那个失败的请求本该成功: 回退看全部的桶)
		if fails.Load() > 0 && given.Load() == 0 && ref["a"] >= 3 {
			t.Errorf("并发 %d: %d 次不够,但最后还剩 %d(假的不够)", round, fails.Load(), ref["a"])
		}
	}
	exec(`TRUNCATE stock CASCADE`)
	var left int
	_ = conn.QueryRow(ctx, `SELECT count(*) FROM bucket_stock`).Scan(&left)
	if left != 0 {
		t.Errorf("TRUNCATE 之后还有桶 %d 个", left)
	}
	if !t.Failed() {
		t.Logf("分桶的元件认证: %d 个检查点全部一致", n)
	}
}
