// Package acceptgen: IR → 自动生成的验收用例(gen/acceptance/<id>.yaml)。只读 IR,和语言无关。
package acceptgen

// 自动生成验收用例(机制测试)。
//
// 循环论证的边界: 这里的期待值和生成的代码来自同一份声明,所以验证不了"声明是否符合业务意图"
// (那是人写的用例和审查的职责)。这里只生成:
//   - validation: proto 的 buf.validate 规则 → 边界值(违反 → INVALID_ARGUMENT,刚好合法 → 不是 INVALID_ARGUMENT)
//
// 查询的正确性由差分测试负责(factory/accept/diff.go: 运行时随机数据 + 核心代数的参考求值器),
// 不在这里合成数据。

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"

	"apifactory/factory/ir"
	"apifactory/factory/kinds"
	"apifactory/factory/spec"
)

// Write: 为 plan 里的每个 API 写自动验收用例。
func Write(plan *ir.Plan) error {
	for i := range plan.APIs {
		if err := writeAPI(plan, &plan.APIs[i]); err != nil {
			return fmt.Errorf("%s: %w", plan.APIs[i].SpecPath, err)
		}
	}
	return nil
}

// ctx: 一个 API 的生成上下文(IR + 领域层的 enum)。
type ctx struct {
	plan *ir.Plan
	api  *ir.API
}

func writeAPI(plan *ir.Plan, api *ir.API) error {
	c := &ctx{plan: plan, api: api}
	a := &spec.AutoAcceptance{Spec: api.SpecPath}

	if suite, cov := c.validationSuite(); len(suite.Cases) > 0 {
		a.Suites = append(a.Suites, suite)
		a.Coverage = append(a.Coverage, cov...)
	}
	switch {
	case api.Pipeline != nil && (api.Pattern == "get_by_id" || api.Pattern == "list_keyset"):
		a.Coverage = append(a.Coverage, "差分测试(运行时): 随机数据 + 核心代数的参考求值器,覆盖筛选 / 排序 / 字段映射 / 翻页",
			"差分测试(运行时): 不合法的随机请求(protovalidate)→ INVALID_ARGUMENT")
		if api.Pattern == "list_keyset" {
			a.Coverage = append(a.Coverage, "差分测试(运行时): 分页出口(途中改 page_size / 途中改筛选条件 / 非法 token / 默认 page_size)")
		}
	case api.Query.Escape:
		a.Coverage = append(a.Coverage, "逃生口 SQL: 没有差分测试(只有人写的用例)")
	}

	path := spec.AutoAcceptancePath(api.ID)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	b, err := yaml.Marshal(a)
	if err != nil {
		return err
	}
	header := "# Code generated by factory from " + api.SpecPath + ". DO NOT EDIT.\n# 机制测试: 期待值来自声明本身,验证的是代码生成/平台,不是业务意图。\n"
	return os.WriteFile(path, append([]byte(header), b...), 0o644)
}

// ---------------------------------------------------------------------------
// validation: buf.validate 规则 → 边界值
// ---------------------------------------------------------------------------

type boundary struct {
	label string
	value any
	valid bool
	unset bool
}

func intBoundaries(gt, gte, lt, lte *int64, in []int64) []boundary {
	var b []boundary
	if gt != nil {
		b = append(b, boundary{fmt.Sprintf("= %d(gt %d 的边界,违反)", *gt, *gt), *gt, false, false},
			boundary{fmt.Sprintf("= %d(gt %d 的边界,合法)", *gt+1, *gt), *gt + 1, true, false})
	}
	if gte != nil {
		b = append(b, boundary{fmt.Sprintf("= %d(gte %d 的边界,违反)", *gte-1, *gte), *gte - 1, false, false},
			boundary{fmt.Sprintf("= %d(gte %d 的边界,合法)", *gte, *gte), *gte, true, false})
	}
	if lt != nil {
		b = append(b, boundary{fmt.Sprintf("= %d(lt %d 的边界,违反)", *lt, *lt), *lt, false, false},
			boundary{fmt.Sprintf("= %d(lt %d 的边界,合法)", *lt-1, *lt), *lt - 1, true, false})
	}
	if lte != nil {
		b = append(b, boundary{fmt.Sprintf("= %d(lte %d 的边界,违反)", *lte+1, *lte), *lte + 1, false, false},
			boundary{fmt.Sprintf("= %d(lte %d 的边界,合法)", *lte, *lte), *lte, true, false})
	}
	if len(in) > 0 {
		mx, mn := in[0], in[0]
		for _, v := range in {
			mx, mn = max(mx, v), min(mn, v)
		}
		b = append(b, boundary{fmt.Sprintf("= %d(不在 in %v 内)", mx+1, in), mx + 1, false, false},
			boundary{fmt.Sprintf("= %d(不在 in %v 内)", mn-1, in), mn - 1, false, false})
		for _, v := range in {
			b = append(b, boundary{fmt.Sprintf("= %d(in %v 内)", v, in), v, true, false})
		}
	}
	return b
}

func boundariesFor(f *ir.Field) ([]boundary, []string) {
	r := f.Rules
	var b []boundary
	var rules []string
	if r.Required {
		b = append(b, boundary{"未指定(required)", nil, false, true})
		rules = append(rules, "required")
	}
	switch r.Type {
	case "int32", "int64":
		b = append(b, intBoundaries(r.Gt, r.Gte, r.Lt, r.Lte, r.In)...)
		rules = append(rules, r.Type+" 范围/in")
	case "enum":
		bad := map[int64]bool{}
		for _, v := range r.NotIn {
			bad[v] = true
			b = append(b, boundary{fmt.Sprintf("= %d(not_in)", v), v, false, false})
		}
		if r.Defined {
			mx := int32(0)
			for _, v := range f.Values {
				mx = max(mx, v.Number)
			}
			b = append(b, boundary{fmt.Sprintf("= %d(未定义的值,defined_only)", mx+1), int64(mx + 1), false, false})
		}
		for _, v := range f.Values {
			if !bad[int64(v.Number)] {
				b = append(b, boundary{fmt.Sprintf("= %s", v.Name), v.Name, true, false})
			}
		}
		rules = append(rules, "enum defined_only/not_in")
	case "string":
		if r.MinLen != nil && *r.MinLen > 0 {
			n := int(*r.MinLen)
			b = append(b, boundary{fmt.Sprintf("长度 %d(min_len %d 的边界,违反)", n-1, n), strings.Repeat("a", n-1), false, false},
				boundary{fmt.Sprintf("长度 %d(min_len %d 的边界,合法)", n, n), strings.Repeat("a", n), true, false})
		}
		if r.MaxLen != nil {
			n := int(*r.MaxLen)
			b = append(b, boundary{fmt.Sprintf("长度 %d(max_len %d 的边界,违反)", n+1, n), strings.Repeat("a", n+1), false, false},
				boundary{fmt.Sprintf("长度 %d(max_len %d 的边界,合法)", n, n), strings.Repeat("a", n), true, false})
		}
		if t, ok := kinds.ByPattern(r.Pattern); ok { // 格式的边界值来自类型的注册表(factory/kinds)
			for _, x := range t.Boundaries {
				b = append(b, boundary{x.Label, x.Value, x.Valid, false})
			}
			rules = append(rules, t.Name+"格式")
		}
		rules = append(rules, "string 长度")
	}
	return b, rules
}

func (c *ctx) validationSuite() (spec.Suite, []string) {
	suite := spec.Suite{Name: "validation"}
	base := c.api.BaseRequest
	if base == nil {
		if c.api.Pattern == "list_keyset" {
			base = map[string]any{}
		} else {
			return suite, []string{"validation: 未生成(没有 code: OK 的人写用例可作为基础请求)"}
		}
	}
	var cov []string
	for i := range c.api.Request.Fields {
		f := &c.api.Request.Fields[i]
		if f.Rules == nil {
			continue
		}
		bs, rules := boundariesFor(f)
		if len(bs) == 0 {
			continue
		}
		cov = append(cov, fmt.Sprintf("validation: %s(%s)", f.Name, strings.Join(rules, ", ")))
		for _, b := range bs {
			req := map[string]any{}
			for k, v := range base {
				req[k] = v
			}
			if b.unset {
				delete(req, f.Name)
			} else {
				req[f.Name] = b.value
			}
			code := "INVALID_ARGUMENT"
			if b.valid {
				code = "!INVALID_ARGUMENT" // 合法输入: 可能是 OK 也可能是 NOT_FOUND,但不能被校验拒绝
			}
			suite.Cases = append(suite.Cases, spec.Case{
				Name:    fmt.Sprintf("%s %s", f.Name, b.label),
				Request: req,
				Expect:  spec.Expect{Code: code},
			})
		}
	}
	if c.api.Request.HasRules {
		cov = append(cov, "validation: 消息级 CEL 规则不自动生成(需要人写用例)")
	}
	return suite, cov
}
