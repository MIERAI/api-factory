func (c *ctx) getByIDSuite() (spec.Suite, []string, error) {
	suite := spec.Suite{Name: "pattern:get_by_id"}
	table := c.api.Table
	filters := c.api.Filters
	cols := c.api.Query.Select
	needed := map[string]bool{}
	for _, c := range cols {
		needed[c] = true
	}
	rows, err := synthesize(c.api.TableColumns, table, 3, synthPlan{enumValues: c.enumPlan()}, needed)
	if err != nil {
		return suite, nil, err
	}
	suite.Fixtures = map[string][]map[string]any{table: fixtureRows(rows)}
	out := messageFieldNames(&c.api.Response)
	for i, r := range rows {
		req := map[string]any{}
		for _, f := range filters {
			req[f.Field] = c.present(f.Column, r[f.Column])
		}
		resp := map[string]any{}
		for _, f := range out {
			resp[f] = c.present(f, r[f])
		}
		suite.Cases = append(suite.Cases, spec.Case{
			Name:    fmt.Sprintf("按键取到第 %d 行,响应字段与列一致", i+1),
			Request: req,
			Expect:  spec.Expect{Code: "OK", Response: resp},
		})
	}
	miss := map[string]any{}
	for _, f := range filters {
		switch kindOf(f.ColumnType) {
		case "int":
			miss[f.Field] = int64(1000)
		case "text":
			miss[f.Field] = "not-found-key"
		default:
			return suite, nil, fmt.Errorf("get_by_id: cannot build a missing key for %s", f.Field)
		}
	}
	suite.Cases = append(suite.Cases, spec.Case{Name: "不存在的键 → NOT_FOUND", Request: miss, Expect: spec.Expect{Code: "NOT_FOUND"}})
	return suite, []string{"get_by_id: 按键取得(响应字段 ↔ 列映射)", "get_by_id: 不存在 → NOT_FOUND"}, nil
}

