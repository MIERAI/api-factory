func (c *ctx) listKeysetSuite() (spec.Suite, []string, error) {
	suite := spec.Suite{Name: "pattern:list_keyset"}
	k := c.api.Keyset
	table := c.api.Table
	desc := k.Desc
	direction := "asc"
	if desc {
		direction = "desc"
	}
	filters := c.api.Filters
	cols := c.api.Query.Select
	needed := map[string]bool{}
	for _, c := range cols {
		needed[c] = true
	}
	// 并列只在 order_by 有多列时才有意义(第一列可以重复,由后面的列决定次序)。
	// order_by 只有一列时,这一列在结果里必须唯一,制造并列反而会违反唯一约束(实测: order_items 的主键)
	plan := synthPlan{eqValues: map[string][]any{}, enumValues: c.enumPlan()}
	if len(k.OrderBy) > 1 {
		plan.tieCol = k.OrderBy[0]
	}
	for _, f := range filters {
		if f.Op == "prefix" && f.Column != plan.tieCol {
			if plan.prefixValues == nil {
				plan.prefixValues = map[string][]any{}
			}
			plan.prefixValues[f.Column] = prefixSamples
		}
		if f.Op == "eq" {
			if cand := c.eqCandidates(f); len(cand) > 0 && f.Column != plan.tieCol {
				plan.eqValues[f.Column] = cand
			}
		}
		needed[f.Column] = true
	}
	rows, err := synthesize(c.api.TableColumns, table, synthRows, plan, needed)
	if err != nil {
		return suite, nil, err
	}
	suite.Fixtures = map[string][]map[string]any{table: fixtureRows(rows)}

	// 必填的筛选条件(没有 presence 的字段)必须出现在每个请求里: 取一个值作为基础
	baseReq, baseVals := map[string]any{}, map[string]any{}
	for _, f := range filters {
		if f.Presence {
			continue
		}
		var v any
		if cand := plan.eqValues[f.Column]; f.Op == "eq" && len(cand) > 0 {
			v = cand[0]
		} else {
			v = rows[len(rows)/2][f.Column]
		}
		baseVals[f.Field] = v
		baseReq[f.Field] = c.present(f.Column, v)
	}
	withBase := func(extra map[string]any) map[string]any {
		out := map[string]any{}
		for k, v := range baseReq {
			out[k] = v
		}
		for k, v := range extra {
			out[k] = v
		}
		return out
	}

	itemName := k.ItemsField
	itemFields := messageFieldNames(c.api.Response.Field(itemName).Message)
	list := func(vals map[string]any) []map[string]any {
		merged := map[string]any{}
		for k, v := range baseVals {
			merged[k] = v
		}
		for k, v := range vals {
			merged[k] = v
		}
		return oracleSort(oracleFilter(rows, filters, merged), k.OrderBy, desc)
	}
	add := func(name string, req map[string]any, resp map[string]any) {
		suite.Cases = append(suite.Cases, spec.Case{Name: name, Request: withBase(req), Expect: spec.Expect{Code: "OK", Response: resp}})
	}
	tokenFor := func(more bool) any {
		if more {
			return "$nonempty"
		}
		return "$absent"
	}
	var cov []string

	// 无筛选: 全部,排序(含并列行的次序),字段映射
	all := list(nil)
	add("可选筛选全部不指定 — 排序与字段映射(含并列行)", map[string]any{},
		map[string]any{itemName: c.items(all, itemFields), "next_page_token": tokenFor(len(all) > int(k.DefaultSize))})
	cov = append(cov, fmt.Sprintf("list_keyset: 排序 %v %s(合成数据含并列值)与字段映射", k.OrderBy, direction))

	key := k.OrderBy[len(k.OrderBy)-1]

	// 每个筛选条件单独
	for _, f := range filters {
		if f.Op == "prefix" {
			if !f.Presence {
				continue // 必填的前缀条件已在基础请求里
			}
			for _, pr := range prefixProbes {
				got := list(map[string]any{f.Field: pr.prefix})
				add(fmt.Sprintf("前缀 %s = %q(%s)", f.Field, pr.prefix, pr.label),
					map[string]any{f.Field: pr.prefix},
					map[string]any{itemName: c.items(got, []string{key})})
			}
			cov = append(cov, fmt.Sprintf("list_keyset: 前缀 %s → %s(%% 和 _ 按字面匹配)", f.Field, f.Column))
			continue
		}
		var vals []any
		switch {
		case plan.eqValues[f.Column] != nil:
			vals = plan.eqValues[f.Column]
		default: // 范围条件: 取中间一行的值做边界
			vals = []any{all[len(all)/2][f.Column]}
		}
		for _, v := range vals {
			got := list(map[string]any{f.Field: v})
			pv := c.present(f.Column, v)
			add(fmt.Sprintf("筛选 %s %s %v", f.Field, f.SQLOp, pv),
				map[string]any{f.Field: pv},
				map[string]any{itemName: c.items(got, []string{key})})
		}
		cov = append(cov, fmt.Sprintf("list_keyset: 筛选 %s → %s %s(presence=%v)", f.Field, f.Column, f.SQLOp, f.Presence))
	}

	// 所有 eq 条件组合: 让执行计划从"按索引顺序扫描"变成"筛选后排序",暴露依赖物理顺序的排序 bug
	combo := map[string]any{}
	for _, f := range filters {
		if vals := plan.eqValues[f.Column]; vals != nil && f.Op == "eq" {
			combo[f.Field] = vals[0]
		}
	}
	if len(combo) >= 2 {
		got := list(combo)
		req := map[string]any{}
		for _, f := range filters {
			if v, ok := combo[f.Field]; ok {
				req[f.Field] = c.present(f.Column, v)
			}
		}
		add("所有 eq 条件组合(筛选后排序,并列行次序)", req, map[string]any{itemName: c.items(got, []string{key})})
		cov = append(cov, "list_keyset: eq 条件组合(不依赖索引顺序的排序)")
	}

	// 翻页走到底: k=1(并列行跨页)、k=3(最后一页不满)、k=n/2(最后一页刚好满)
	for _, size := range []int{1, 3, synthRows / 2} {
		var steps []spec.Step
		for start := 0; start < len(all); start += size {
			end := min(start+size, len(all))
			req := withBase(map[string]any{"page_size": size})
			if start > 0 {
				req["page_token"] = "$prev.next_page_token"
			}
			steps = append(steps, spec.Step{Request: req, Expect: spec.Expect{Code: "OK",
				Response: map[string]any{itemName: c.items(all[start:end], []string{key}), "next_page_token": tokenFor(end < len(all))}}})
		}
		suite.Cases = append(suite.Cases, spec.Case{Name: fmt.Sprintf("翻页走到底 page_size=%d", size), Steps: steps})
	}
	cov = append(cov, "list_keyset: 翻页(并列行跨页 / 最后一页不满 / 最后一页刚好满)")

	// 翻页途中改 page_size 是允许的
	if len(all) >= 5 {
		suite.Cases = append(suite.Cases, spec.Case{Name: "翻页途中改 page_size 是允许的", Steps: []spec.Step{
			{Request: withBase(map[string]any{"page_size": 2}), Expect: spec.Expect{Code: "OK", Response: map[string]any{itemName: c.items(all[:2], []string{key}), "next_page_token": "$nonempty"}}},
			{Request: withBase(map[string]any{"page_size": 3, "page_token": "$prev.next_page_token"}), Expect: spec.Expect{Code: "OK", Response: map[string]any{itemName: c.items(all[2:5], []string{key})}}},
		}})
	}
	// 翻页途中改筛选条件 → 旧 token 失效
	for _, f := range filters {
		if vals := plan.eqValues[f.Column]; len(vals) >= 2 && f.Op == "eq" {
			suite.Cases = append(suite.Cases, spec.Case{Name: fmt.Sprintf("翻页途中改筛选条件(%s) → INVALID_ARGUMENT", f.Field), Steps: []spec.Step{
				{Request: withBase(map[string]any{f.Field: c.present(f.Column, vals[0]), "page_size": 1}), Expect: spec.Expect{Code: "OK", Response: map[string]any{"next_page_token": "$nonempty"}}},
				{Request: withBase(map[string]any{f.Field: c.present(f.Column, vals[1]), "page_size": 1, "page_token": "$prev.next_page_token"}), Expect: spec.Expect{Code: "INVALID_ARGUMENT", MessageContains: "page_token"}},
			}})
			break
		}
	}
	suite.Cases = append(suite.Cases, spec.Case{Name: "非法 page_token → INVALID_ARGUMENT",
		Request: withBase(map[string]any{"page_token": "not-a-valid-token"}), Expect: spec.Expect{Code: "INVALID_ARGUMENT", MessageContains: "page_token"}})
	cov = append(cov, "list_keyset: page_token(改 page_size 允许 / 改筛选条件失效 / 非法 token)")
	return suite, cov, nil
}
