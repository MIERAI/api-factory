// Package acceptgen: IR → 自动生成的验收用例(gen/acceptance/<id>.yaml)。只读 IR,和语言无关。
package acceptgen

// 自动生成验收用例(机制测试)。
//
// 循环论证的边界: 这里的期待值和生成的代码来自同一份声明,所以验证不了"声明是否符合业务意图"
// (那是人写的用例和审查的职责)。这里只生成:
//   - validation: proto 的 buf.validate 规则 → 边界值(违反 → INVALID_ARGUMENT,刚好合法 → 不是 INVALID_ARGUMENT)
//
// 查询的正确性由差分测试负责(factory/accept/diff.go: 运行时随机数据 + 核心代数的参考求值器),
// 不在这里合成数据。

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"

	"apifactory/factory/constraints"
	"apifactory/factory/exits"
	"apifactory/factory/ir"
	"apifactory/factory/spec"
)

// Write: 为 plan 里的每个 API 写自动验收用例。
func Write(plan *ir.Plan) error {
	for i := range plan.APIs {
		if err := writeAPI(plan, &plan.APIs[i]); err != nil {
			return fmt.Errorf("%s: %w", plan.APIs[i].SpecPath, err)
		}
	}
	return nil
}

// ctx: 一个 API 的生成上下文(IR + 领域层的 enum)。
type ctx struct {
	plan *ir.Plan
	api  *ir.API
}

func writeAPI(plan *ir.Plan, api *ir.API) error {
	c := &ctx{plan: plan, api: api}
	a := &spec.AutoAcceptance{Spec: api.SpecPath}

	if suite, cov := c.validationSuite(); len(suite.Cases) > 0 {
		a.Suites = append(a.Suites, suite)
		a.Coverage = append(a.Coverage, cov...)
	}
	ex, _ := exits.ByKind(api.Pattern)
	switch {
	case api.Pipeline != nil && ex != nil && ex.DiffCase != nil:
		a.Coverage = append(a.Coverage, "差分测试(运行时): 随机数据 + 核心代数的参考求值器,覆盖筛选 / 排序 / 字段映射 / "+ex.Name+"的出口",
			"差分测试(运行时): 不合法的随机请求(protovalidate)→ INVALID_ARGUMENT")
		if ex.DiffExtra != nil {
			a.Coverage = append(a.Coverage, "差分测试(运行时): "+ex.Name+"出口自己的用例")
		}
	case api.Query.Escape:
		a.Coverage = append(a.Coverage, "逃生口 SQL: 没有差分测试(只有人写的用例)")
	}

	path := spec.AutoAcceptancePath(api.ID)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	b, err := yaml.Marshal(a)
	if err != nil {
		return err
	}
	header := "# Code generated by factory from " + api.SpecPath + ". DO NOT EDIT.\n# 机制测试: 期待值来自声明本身,验证的是代码生成/平台,不是业务意图。\n"
	return os.WriteFile(path, append([]byte(header), b...), 0o644)
}

// ---------------------------------------------------------------------------
// validation: buf.validate 规则 → 边界值
// ---------------------------------------------------------------------------

// boundariesFor: 必填(proto 的结构)+ 约束的注册表(factory/constraints)给出的边界值。
func boundariesFor(f *ir.Field, base map[string]any) ([]constraints.Boundary, []string) {
	var b []constraints.Boundary
	var rules []string
	if f.Rules.Required {
		b = append(b, constraints.Boundary{Label: "未指定(required)", Unset: true})
		rules = append(rules, "required")
	}
	cb, cr := constraints.Boundaries(f, base)
	return append(b, cb...), append(rules, cr...)
}

func (c *ctx) validationSuite() (spec.Suite, []string) {
	suite := spec.Suite{Name: "validation"}
	base := c.api.BaseRequest
	if base == nil {
		if ex, ok := exits.ByKind(c.api.Pattern); ok && ex.EmptyRequest { // 空请求可以作为基础请求(分页)
			base = map[string]any{}
		} else {
			return suite, []string{"validation: 未生成(没有 code: OK 的人写用例可作为基础请求)"}
		}
	}
	var cov []string
	for i := range c.api.Request.Fields {
		f := &c.api.Request.Fields[i]
		if f.Rules == nil {
			continue
		}
		bs, rules := boundariesFor(f, base)
		if len(bs) == 0 {
			continue
		}
		cov = append(cov, fmt.Sprintf("validation: %s(%s)", f.Name, strings.Join(rules, ", ")))
		for _, b := range bs {
			req := map[string]any{}
			for k, v := range base {
				req[k] = v
			}
			if b.Unset {
				delete(req, f.Name)
			} else {
				req[f.Name] = b.Value
			}
			code := "INVALID_ARGUMENT"
			if b.Valid {
				code = "!INVALID_ARGUMENT" // 合法输入: 可能是 OK 也可能是 NOT_FOUND,但不能被校验拒绝
			}
			suite.Cases = append(suite.Cases, spec.Case{
				Name:    fmt.Sprintf("%s %s", f.Name, b.Label),
				Request: req,
				Expect:  spec.Expect{Code: code},
			})
		}
	}
	if c.api.Request.HasRules {
		cov = append(cov, "validation: 消息级 CEL 规则不自动生成(需要人写用例)")
	}
	return suite, cov
}
