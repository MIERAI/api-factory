type synthPlan struct {
	eqValues     map[string][]any // 列 → 轮流取的值(eq 筛选列,同一并列组共享)
	prefixValues map[string][]any // 列 → 逐行轮流取的值(前缀匹配列: 每个样本都要出现)
	enumValues   map[string][]any // 列 → 领域层定义的 DB 值(enum 列)
	tieCol       string           // 制造并列值的列(keyset 的第一排序列)
}

func (c *ctx) enumDBValues(column string) []any {
	e := c.plan.Enum(c.api.Table, column)
	if e == nil {
		return nil
	}
	var out []any
	for _, v := range e.Values {
		out = append(out, v.DB)
	}
	return out
}

func (c *ctx) enumPlan() map[string][]any {
	out := map[string][]any{}
	for _, col := range c.api.TableColumns {
		if vals := c.enumDBValues(col.Name); vals != nil {
			out[col.Name] = vals
		}
	}
	return out
}

func (c *ctx) eqCandidates(f ir.Filter) []any {
	if vals := c.enumDBValues(f.Column); vals != nil {
		return vals
	}
	if fd := c.api.Request.Field(f.Field); fd != nil && fd.Rules != nil && len(fd.Rules.In) > 0 && (fd.Rules.Type == "int32" || fd.Rules.Type == "int64") {
		var out []any
		for _, v := range fd.Rules.In {
			out = append(out, v)
		}
		return out
	}
	switch kindOf(f.ColumnType) {
	case "int":
		return []any{int64(1), int64(2), int64(3)}
	case "text":
		return []any{"alpha", "beta"}
	case "bool":
		return []any{true, false}
	}
	return nil
}

func kindOf(sqlType string) string {
	switch sqlType {
	case "int2", "int4", "int8", "smallint", "integer", "bigint", "serial", "bigserial":
		return "int"
	case "text", "varchar", "bpchar", "char":
		return "text"
	case "timestamptz", "timestamp":
		return "time"
	case "bool", "boolean":
		return "bool"
	}
	return ""
}

// synthesize: 为 table 合成 n 行。eq 筛选列轮流取候选值;tieCol 每两行取同一个值(制造并列);
// 其他 NOT NULL 列按类型取唯一值;可空且用不到的列为 NULL。
func synthesize(columns []ir.Column, table string, n int, plan synthPlan, needed map[string]bool) ([]map[string]any, error) {
	var rows []map[string]any
	for i := 0; i < n; i++ {
		row := map[string]any{}
		group := i // 并列组: tieCol 有值时每两行一组
		if plan.tieCol != "" {
			group = i / 2
		}
		for _, c := range columns {
			if vals, ok := plan.prefixValues[c.Name]; ok {
				row[c.Name] = vals[i%len(vals)]
				continue
			}
			if vals, ok := plan.eqValues[c.Name]; ok {
				// 同一并列组共享筛选值: 筛选后的结果里也必须有并列行,否则"并列时的次级排序"测不到
				row[c.Name] = vals[group%len(vals)]
				continue
			}
			if vals, ok := plan.enumValues[c.Name]; ok {
				row[c.Name] = vals[i%len(vals)] // 每个 enum 值都出现,映射表的每一项都被验证
				continue
			}
			if !c.NotNull && !needed[c.Name] {
				continue
			}
			step := i
			if c.Name == plan.tieCol {
				step = i / 2
			}
			switch kindOf(c.Type) {
			case "int":
				row[c.Name] = int64(step + 1)
			case "text":
				row[c.Name] = fmt.Sprintf("v%02d", step+1)
			case "time":
				row[c.Name] = synthBase.Add(time.Duration(step) * time.Hour)
			case "bool":
				row[c.Name] = step%2 == 0
			default:
				return nil, fmt.Errorf("cannot synthesize column %s.%s of type %s", table, c.Name, c.Type)
			}
		}
		rows = append(rows, row)
	}
	return rows, nil
}

func fixtureRows(rows []map[string]any) []map[string]any {
	var out []map[string]any
	for _, r := range rows {
		m := map[string]any{}
		for k, v := range r {
			m[k] = jsonValue(v)
		}
		out = append(out, m)
	}
	return out
}

// present: 请求 / 期待值里的表示。enum 列: DB 值 → proto 值名(protojson 输出的是名字)。
func (c *ctx) present(column string, v any) any {
	if e := c.plan.Enum(c.api.Table, column); e != nil {
		if n, ok := v.(int64); ok {
			for _, ev := range e.Values {
				if ev.DB == n {
					return ev.Name
				}
			}
		}
	}
	return jsonValue(v)
}

// jsonValue: fixture / 请求 / 期待值里的表示(时间 → RFC3339 UTC,与 protojson 一致)。
func jsonValue(v any) any {
	if t, ok := v.(time.Time); ok {
		return t.UTC().Format(time.RFC3339)
	}
	return v
}

func compare(a, b any) int {
	switch x := a.(type) {
	case int64:
		y := b.(int64)
		switch {
		case x < y:
			return -1
		case x > y:
			return 1
		}
		return 0
	case string:
		return strings.Compare(x, b.(string))
	case time.Time:
		return x.Compare(b.(time.Time))
	case bool:
		y := b.(bool)
		switch {
		case x == y:
			return 0
		case !x:
			return -1
		}
		return 1
	}
	panic(fmt.Sprintf("compare: unsupported %T", a))
}

func opHolds(op string, c int) bool {
	switch op {
	case "eq":
		return c == 0
	case "gt":
		return c > 0
	case "gte":
		return c >= 0
	case "lt":
		return c < 0
	case "lte":
		return c <= 0
	}
	return false
}

// prefixSamples: 前缀匹配列的合成值。故意包含 % 和 _,验证它们按字面匹配而不是通配符。
var prefixSamples = []any{"apple", "apricot", "banana", "a%c", "a_c", "abc"}

// prefixProbes: 前缀 → 说明。期待值由参考实现(strings.HasPrefix)计算
var prefixProbes = []struct{ prefix, label string }{
	{"ap", "普通前缀"},
	{"a%", "% 按字面匹配(不是通配符)"},
	{"a_", "_ 按字面匹配(不是通配符)"},
}

// oracleFilter: 参考实现。values 里没有的筛选条件视为未指定。
func oracleFilter(rows []map[string]any, filters []ir.Filter, values map[string]any) []map[string]any {
	var out []map[string]any
	for _, r := range rows {
		ok := true
		for _, f := range filters {
			v, given := values[f.Field]
			if !given {
				continue
			}
			if f.Op == "prefix" {
				if !strings.HasPrefix(r[f.Column].(string), v.(string)) {
					ok = false
					break
				}
				continue
			}
			if !opHolds(f.Op, compare(r[f.Column], v)) {
				ok = false
				break
			}
		}
		if ok {
			out = append(out, r)
		}
	}
	return out
}

func oracleSort(rows []map[string]any, orderBy []string, desc bool) []map[string]any {
	out := append([]map[string]any(nil), rows...)
	sort.SliceStable(out, func(i, j int) bool {
		for _, c := range orderBy {
			if d := compare(out[i][c], out[j][c]); d != 0 {
				if desc {
					return d > 0
				}
				return d < 0
			}
		}
		return false
	})
	return out
}

func (c *ctx) items(rows []map[string]any, fields []string) []any {
	out := []any{}
	for _, r := range rows {
		m := map[string]any{}
		for _, f := range fields {
			if v, ok := r[f]; ok {
				m[f] = c.present(f, v)
			}
		}
		out = append(out, m)
	}
	return out
}

func messageFieldNames(m *ir.Message) []string {
	var out []string
	for _, f := range m.Fields {
		out = append(out, f.Name)
	}
	return out
}

