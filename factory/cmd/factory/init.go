package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"apifactory/factory/proj"
)

// factory init <dir> --module M [--name N]: a new project — another repository / another database the factory generates
// a service for (factory --project <dir> design|prepare|… afterwards). The project gets what this repository has at
// its root and the factory does not generate: go.mod (the generated code's module, the protoc plugins as tools, the
// public runtime), the buf configuration, cmd/server/main.go, and factory.yaml with only the project's keys (the proto
// package prefix; models and the adapter come from the factory). design/ and db/schema/ are for the designer.
func cmdInit(args []string) error {
	fs := flag.NewFlagSet("init", flag.ExitOnError)
	module := fs.String("module", "", "Go module of the project (e.g. github.com/you/shop/services/catalog)")
	name := fs.String("name", "", "proto package prefix (default: the directory's name); packages become <name>.<domain>.v1")
	var dir string
	if len(args) > 0 && !strings.HasPrefix(args[0], "-") {
		dir, args = args[0], args[1:]
	}
	fs.Parse(args)
	if dir == "" || *module == "" {
		return errors.New("usage: factory init <dir> --module <go module> [--name <proto prefix>]")
	}
	if *name == "" {
		*name = filepath.Base(dir)
	}
	if !regexp.MustCompile(`^[a-z][a-z0-9_]*$`).MatchString(*name) {
		return fmt.Errorf("--name %q: a proto package segment (lower case, digits, _)", *name)
	}
	if entries, err := os.ReadDir(dir); err == nil && len(entries) > 0 {
		return fmt.Errorf("%s exists and is not empty", dir)
	}

	home := proj.HomePath(".")
	gomod, err := os.ReadFile(filepath.Join(home, "go.mod"))
	if err != nil {
		return err
	}
	files := map[string]string{
		"go.mod":             projectGoMod(string(gomod), *module),
		"factory.yaml":       fmt.Sprintf("# This project's settings; everything else (AI models, the adapter) comes from the factory's factory.yaml.\nproto:\n  package_prefix: %s\n", *name),
		"cmd/server/main.go": "package main\n\nimport \"github.com/MIERAI/api-factory-runtime/server\"\n\nfunc main() {\n\tserver.Run(services)\n}\n",
		".gitignore":         "bin/\n.factory/\n",
		"design/.gitkeep":    "",
		"db/schema/.gitkeep": "",
		"README.md": fmt.Sprintf("# %s\n\nA service generated by api-factory. The designer writes `design/<domain>/` and `db/schema/*.sql`; everything\nelse (`specs/`, `proto/`, `db/queries/`, `gen/`, `internal/handler/`, `cmd/server/wiring_gen.go`) is generated:\n\n```sh\nfactory --project . design    # design/ → proto + specs\nfactory --project . check\nfactory --project . prepare   # → generated code\ngo mod tidy && go build ./...\n```\n", *name),
	}
	for _, f := range []string{"buf.yaml", "buf.lock", "buf.gen.yaml", "go.sum"} { // same toolchain as the factory
		b, err := os.ReadFile(filepath.Join(home, f))
		if err != nil {
			return err
		}
		files[f] = string(b)
	}
	for path, content := range files {
		p := filepath.Join(dir, path)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			return err
		}
	}
	fmt.Printf("✓ project %s (module %s, proto %s.*): write design/ and db/schema/, then factory --project %s design\n", dir, *module, *name, dir)
	return nil
}

// projectGoMod: the factory's go.mod with the project's module line and only what generated code needs: the Go
// version, the protoc plugins (tool), and the requirements of the generated code and the runtime (go mod tidy trims).
func projectGoMod(factory, module string) string {
	goVersion := regexp.MustCompile(`(?m)^go (\S+)`).FindStringSubmatch(factory)
	need := []string{"github.com/MIERAI/api-factory-runtime", "connectrpc.com/connect", "connectrpc.com/validate",
		"github.com/jackc/pgx/v5", "google.golang.org/protobuf", "buf.build/gen/go/bufbuild/protovalidate/protocolbuffers/go"}
	var req []string
	for _, m := range need {
		if v := regexp.MustCompile(`(?m)^\s+` + regexp.QuoteMeta(m) + `\s+(\S+)`).FindStringSubmatch(factory); v != nil {
			req = append(req, "\t"+m+" "+v[1])
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "module %s\n\n", module)
	if goVersion != nil {
		fmt.Fprintf(&b, "go %s\n\n", goVersion[1])
	}
	b.WriteString("tool (\n\tconnectrpc.com/connect/cmd/protoc-gen-connect-go\n\tgoogle.golang.org/protobuf/cmd/protoc-gen-go\n)\n\n")
	fmt.Fprintf(&b, "require (\n%s\n)\n", strings.Join(req, "\n"))
	return b.String()
}
