// StateFile: 当前状态表的 DDL(docs/design/current-state.md)。确定性生成,走项目的迁移流程(和 zz_factory_platform.sql 一样);
// 内容幂等(对已有的库执行 = 迁移,含回填)。
var StateFile = filepath.Join("db", "schema", "zz_factory_current.sql")

const stateHead = `-- Code generated by factory (factory prepare). DO NOT EDIT.
-- 当前状态表: 存储: JSON版本 的逻辑表的每键最新(docs/design/current-state.md)。原始表上的触发器在同一个事务里维护。
-- 这个文件是幂等的: 对已有的库执行 = 建表 + 触发器 + 回填。迁移(db/migrations)= 这个文件的内容 + Down。
`

// writeStateSQL: 每个有当前状态表的 JSON版本 逻辑表的 DDL;索引 = 键 + 读它的 API 用到的列。没有 → 删掉文件。
func writeStateSQL(specs []*spec.Spec, apis []ir.API, cat *catalog, lib *cells.Library) error {
	type ent struct {
		view string
		e    spec.Entity
	}
	byView := map[string]ent{}
	for _, s := range specs {
		if s.Domain == nil {
			continue
		}
		for name, e := range s.Domain.Entities {
			if e.Storage != nil && e.Storage.State != "" {
				byView[name] = ent{name, e}
			}
		}
	}
	if len(byView) == 0 {
		if err := os.Remove(StateFile); err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}
	index := map[string][][]string{}
	for _, a := range apis {
		if a.Pipeline == nil {
			continue
		}
		for st, groups := range core.StateIndexCols(a.Pipeline) {
			index[st] = append(index[st], groups...)
		}
	}
	views := make([]string, 0, len(byView))
	for v := range byView {
		views = append(views, v)
	}
	sort.Strings(views)
	var b strings.Builder
	b.WriteString(stateHead)
	for _, v := range views {
		e := byView[v].e
		src, ok := sources.ByKind(e.Storage.Kind)
		if !ok {
			return fmt.Errorf("表 %s: 存储 %s 不存在", v, e.Storage.Kind)
		}
		scan, err := scanStep(e.Storage.Table, cat)
		if err != nil {
			return err
		}
		steps, err := src.Steps(e.Storage, e.NaturalKey, scan, lib)
		if err != nil {
			return fmt.Errorf("表 %s 的来源: %w", v, err)
		}
		ddl, err := core.StateDDL(steps, dedupe(index[e.Storage.State]))
		if err != nil {
			return fmt.Errorf("表 %s: %w", v, err)
		}
		b.WriteString("\n" + ddl)
	}
	if old, err := os.ReadFile(StateFile); err == nil && string(old) == b.String() {
		return nil
	}
	return os.WriteFile(StateFile, []byte(b.String()), 0o644)
}

func dedupe(groups [][]string) [][]string {
	seen := map[string]bool{}
	var out [][]string
	for _, g := range groups {
		k := strings.Join(g, "\x00")
		if !seen[k] {
			seen[k] = true
			out = append(out, g)
		}
	}
	sort.Slice(out, func(i, j int) bool { return strings.Join(out[i], ",") < strings.Join(out[j], ",") })
	return out
}
