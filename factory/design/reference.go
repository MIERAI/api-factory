package design

// 设计语言的参考(docs/design-language.md): 从各注册表生成,不手写。
// 设计语言能写什么 = 这份文档里的东西;写不了的是"外"(docs/memo/out-of-scope.md)或逃生口。
// make check 用 factory doc --check 确认文档是最新的(注册表改了却没重新生成 → 失败)。

import (
	"fmt"
	"sort"
	"strings"

	"apifactory/factory/cells"
	"apifactory/factory/constraints"
	"apifactory/factory/exits"
	"apifactory/factory/kinds"
	"apifactory/factory/sources"
)

func Reference() (string, error) {
	lib, err := cells.Load()
	if err != nil {
		return "", err
	}
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	row := func(cells ...string) { w("| %s |\n", strings.Join(cells, " | ")) }
	code := func(xs []string) string {
		if len(xs) == 0 {
			return "—"
		}
		var out []string
		for _, x := range xs {
			out = append(out, "`"+x+"`")
		}
		return strings.Join(out, " ")
	}

	w("# 设计语言的参考\n\n")
	w("<!-- Code generated by factory doc. DO NOT EDIT. 来源: 各注册表(factory/exits, sources, kinds, constraints, cells)。 -->\n\n")
	w("设计稿(`design/<领域>/<API>.yaml`)能写的全部东西。这里没有的写法,工厂不支持:\n")
	w("要么是\"外\"(docs/memo/out-of-scope.md),要么用逃生口(手写 SQL / 自定义),要么先给工厂加一种(注册表里加一个文件)。\n\n")

	w("## 顶层的键\n\n%s\n\n", code(TopKeys()))

	w("## 种类(出口)\n\n各种类另外可以写的键。AI = 有 AI 写的部分(纯函数 / 整个 handler)。\n\n")
	row("种类", "内部名", "返回", "另外的键", "AI")
	row("---", "---", "---", "---", "---")
	ex := exits.All()
	sort.Slice(ex, func(i, j int) bool { return ex[i].Kind < ex[j].Kind })
	for _, e := range ex {
		card := map[string]string{"one": "一行", "many": "多行"}[e.Cardinality]
		if card == "" || e.Cell == "" { // 自定义: 由 AI 决定
			card = "—"
		}
		ai := ""
		if e.AI {
			ai = "✓"
		}
		row(e.Name, "`"+e.Kind+"`", card, code(e.DesignKeys), ai)
	}

	w("\n## 数据来源(领域的 存储)\n\n不写 = 普通的表。\n\n")
	row("存储", "内部名", "领域里另外的键", "字段的键", "取数的流水线")
	row("---", "---", "---", "---", "---")
	for _, s := range sources.All() {
		steps := "—"
		if sc, ok := lib.Sources[s.Name]; ok {
			var xs []string
			for _, st := range sc.Steps {
				for k, v := range st {
					xs = append(xs, k+" "+v)
				}
			}
			steps = strings.Join(xs, " → ")
		}
		name := s.Name
		if name == "" {
			name = "(不写: 普通的表)"
		}
		row(name, "`"+s.Kind+"`", code(s.DesignKeys), code(s.FieldKeys), steps)
	}

	w("\n## 类型\n\n输入 / 输出 / 列的类型。后面加「列表」= 多个(输入)。派生的类型继承基本类型,另外带格式。\n\n")
	row("类型", "内部 ID", "基于", "proto", "列的 SQL 类型", "格式")
	row("---", "---", "---", "---", "---", "---")
	for _, t := range kinds.All() {
		base, sql, pat := t.Base, t.CanonicalSQL(), t.Pattern
		if base == "" {
			base = "—"
		}
		if sql == "" {
			sql = "—"
		}
		if pat == "" {
			pat = "—"
		} else {
			pat = "`" + pat + "`"
		}
		row(t.Name, "`"+t.ID+"`", base, "`"+t.Proto+"`", "`"+sql+"`", pat)
	}

	w("\n## 输入的键\n\n%s(必填: 是 / 否;筛选: `列 单元`,见下)。约束:\n\n", code(InputKeys()))
	for _, f := range constraints.Forms() {
		w("- `%s`\n", f)
	}
	w("\n范围 / 长度 / 格式 用在列表上时是每个元素的约束;个数只能用于列表。\n")

	w("\n## 输出的键\n\n一列只写说明(字符串)时,类型和值来自数据来源的同名列。也可以写: %s\n", code(OutputKeys()))
	w("\n`来自: 列名` = 改名(API 的名字和数据的列名不同)。`筛选` 和 `每组取一条` 写数据的列名,`排序` 写 API 的名字(排序在输出之后)。计算 / 自定义 的输出不能改名(由 AI 的代码决定)。\n")

	w("\n## 关联(多对一查找)\n\n`关联:` 下面一项一个(按书写顺序执行),每项可以写: %s。核心的元件 `lookup`。\n\n", code(LookupKeys()))
	w("```yaml\n关联:\n  warehouse: { 表: warehouses, 条件: [warehouse_code = warehouse_code], 列: { warehouse_name: name, region_code: region_code } }\n  region:    { 表: regions, 条件: [region_code = region_code], 列: { region_name: name }, 找不到时: 丢弃 }\n```\n\n")
	w("- `条件`: `当前行的列 = 对方的列`,多列的键写多项。对方的列必须构成对方的表的**主键或唯一约束**(最多一行匹配;不是 → 编译失败)。任一边为空 → 找不到\n")
	w("- `列`: `{ 新列名: 对方的列 }`(或 `[列, …]` = 同名)。加的列之后和数据来源的列一样: `输出`、`来自`、`筛选`、`固定条件`、`排序` 都可以用\n")
	w("- `找不到时`: `保留`(默认: 加的列为空,输出可以不设置)/ `丢弃`(这一行不要)\n")
	w("- 链式: 后面的关联可以用前面的关联加的列做条件。关联的表必须在同一个库里;分库的表只能关联同一个分库的表(条件里有两边的分库键相等)\n")
	w("- 还不支持: 关联 存储: JSON版本 的逻辑表、加的列是枚举\n")

	w("\n## 嵌套(一对多: 子行的列表)\n\n`嵌套:` 下面一项一个,每项可以写: %s。核心的元件 `nest`。名字 = 输出的列名(在 `输出` 里写说明),响应里是 repeated 的子行消息。\n\n", code(NestKeys()))
	w("```yaml\n嵌套:\n  items:\n    表: order_items\n    条件: [id = order_id]\n    固定条件: qty > 0          # 可以不写;子表的列\n    排序: [line_no 小到大]\n    上限: 50\n    列: [line_no, sku, qty, price]   # 或 { 新列名: 子表的列 }\n    行名: OrderItem            # 可以不写: 子表名的单数 PascalCase\n```\n\n")
	w("- `条件`: `当前行的列 = 子表的列`(多列写多项;任一边为空 → 不相等)。当前行的列可以是关联加的列\n")
	w("- `排序`: 子行的顺序必须是全序 —— 排序的列(加上 `条件` 里子表的列)要包含子表的主键或唯一键,否则编译失败\n")
	w("- `上限`: 子行多于上限 → **整个请求返回错误**(FAILED_PRECONDITION),不截断。没有子行 → 空列表 `[]`(不是空值)。例子里写 `结果: 超过上限`\n")
	w("- 值的表示和普通的列一样: 十进制是文本(不丢精度)、时间是 UTC、日期是 YYYY-MM-DD。只有一层(子行里不能再嵌套);子行的列不能是枚举\n")
	w("- 可以和 按键取一条 / 多条 / 一览 / 前N条 组合(分页作用在父行上;只检查响应里的行)。子表必须在同一个库里(分库: 条件里有两边的分库键相等)\n")

	w("\n## 子聚合(按父行聚合)\n\n`子聚合:` 下面一项一个(一项一个聚合),每项可以写: %s。核心的元件 `child_agg`;名字 = 加的列(之后和数据来源的列一样: 输出、筛选、排序)。\n\n", code(ChildAggKeys()))
	w("```yaml\n子聚合:\n  item_count:  { 表: order_items, 条件: [id = order_id], 计算: 件数 }\n  items_total: { 表: order_items, 条件: [id = order_id], 计算: 合计(amount) }\n  first_sku:   { 表: order_items, 条件: [id = order_id], 固定条件: qty > 1, 计算: 最小(sku) }\n```\n\n")
	w("| 计算 | 类型 | 没有子行 | 空值 |\n|---|---|---|---|\n")
	w("| `件数` | 整数64 | 0 | 数的是行数 |\n| `合计(列)` | 整数 → 整数64(溢出 → 查询失败);十进制 → 十进制(精确) | **0**(不是空值) | 忽略;全部为空 → 0 |\n")
	w("| `最小(列)` / `最大(列)` | 列的类型(文本按字节比较) | 空值(输出可以不设置) | 忽略;全部为空 → 空值 |\n\n")
	w("只有 件数 / 合计 / 最小 / 最大(和顶层的分组共用一套聚合: factory/core/agg.go)。合计里不能写表达式(数量 × 单价 请用数据库的生成列,例: storefront v2 的 order_items.amount)。\n")
	w("\n## 分组 / 排名\n\n%s 可以写(多条 / 前N条 / 一览)。筛选之后分组: 每组一行 = 分组键 + 计算的值;之后的 `输出` / `排序` 只能用分组键、计算、排名的输出名(不能写 `来自`)。\n\n", code(exits.GroupKeys))
	w("```yaml\n分组: { 键: [store_code], 计算: { total: 合计(amount), lines: 件数 } }\n排名: { 排序: [total 大到小], 输出: rank }\n排序: [rank 小到大, store_code 小到大]\n```\n\n")
	w("- 分组键为空的行是一组(不是每个空值一组)。没有输入行 → 没有输出行(不输出合计 0 的行)\n")
	w("- `排序` 必须包含全部分组键(不同的组的顺序要确定;前N条 / 一览 都依赖它)\n")
	w("- 排名 = SQL 的 RANK(): 排序的值相同 → 同名次,下一个名次跳过(1, 2, 2, 4)。只能和 分组 一起写\n\n")
	row("计算", "内部名", "规则(factory/core/agg.go)")
	row("---", "---", "---")
	for _, a := range exits.AggWords {
		row(a.Word, "`"+a.Func+"`", a.Desc)
	}

	w("\n## 筛选的单元\n\n输入的 `筛选: <列> <单元>`。定义是基本元件的组合(factory/core)。值没有指定时不筛选(必填时恒筛选)。列表的输入(属于): 不传和空列表都是「没有指定」(proto 分不出两者),不筛选;要求至少 1 个时写 `必填: 是` 或 `个数: \"1~N\"`。\n\n")
	row("单元", "内部名", "定义")
	row("---", "---", "---")
	names := lib.FilterNames()
	for _, n := range names {
		id, _ := lib.FilterID(n)
		row(n, "`"+id+"`", "`"+lib.Filters[n]+"`")
	}

	w("\n## 输入之间的规则\n\n`输入之间的规则:` 下面一行一条。\n\n")
	for _, f := range constraints.RelationForms() {
		w("- `%s`\n", f)
	}
	return b.String(), nil
}
