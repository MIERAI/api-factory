func sortedKeys(m map[string]string) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func Reference() (string, error) {
	lib, err := cells.Load()
	if err != nil {
		return "", err
	}
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	row := func(cells ...string) { w("| %s |\n", strings.Join(cells, " | ")) }
	code := func(xs []string) string {
		if len(xs) == 0 {
			return "—"
		}
		var out []string
		for _, x := range xs {
			out = append(out, "`"+x+"`")
		}
		return strings.Join(out, " ")
	}

	w("# 设计语言的参考\n\n")
	w("<!-- Code generated by factory doc. DO NOT EDIT. 来源: 各注册表(factory/exits, sources, kinds, constraints, cells)。 -->\n\n")
	w("设计稿(`design/<领域>/<API>.yaml`)能写的全部东西。这里没有的写法,工厂不支持:\n")
	w("要么是\"外\"(docs/memo/out-of-scope.md),要么用逃生口(手写 SQL / 自定义),要么先给工厂加一种(注册表里加一个文件)。\n\n")

	w("## 顶层的键\n\n%s\n\n", code(TopKeys()))

	w("## 种类(出口)\n\n各种类另外可以写的键。AI = 有 AI 写的部分(纯函数 / 整个 handler)。\n\n")
	row("种类", "内部名", "返回", "另外的键", "AI")
	row("---", "---", "---", "---", "---")
	ex := exits.All()
	sort.Slice(ex, func(i, j int) bool { return ex[i].Kind < ex[j].Kind })
	for _, e := range ex {
		if e.Command { // 命令: 下面单独一节
			continue
		}
		card := map[string]string{"one": "一行", "many": "多行"}[e.Cardinality]
		if card == "" || e.Cell == "" { // 自定义: 由 AI 决定
			card = "—"
		}
		ai := ""
		if e.AI {
			ai = "✓"
		}
		row(e.Name, "`"+e.Kind+"`", card, code(e.DesignKeys), ai)
	}

	commandReference(w, row, code)

	w("\n## 数据来源(领域的 存储)\n\n不写 = 普通的表。\n\n")
	row("存储", "内部名", "领域里另外的键", "字段的键", "取数的流水线")
	row("---", "---", "---", "---", "---")
	for _, s := range sources.All() {
		steps := "—"
		if sc, ok := lib.Sources[s.Name]; ok {
			var xs []string
			for _, st := range sc.Steps {
				for k, v := range st {
					xs = append(xs, k+" "+v)
				}
			}
			steps = strings.Join(xs, " → ")
		}
		name := s.Name
		if name == "" {
			name = "(不写: 普通的表)"
		}
		row(name, "`"+s.Kind+"`", code(s.DesignKeys), code(s.FieldKeys), steps)
	}

	w("\n## 类型\n\n输入 / 输出 / 列的类型。后面加「列表」= 多个(输入)。派生的类型继承基本类型,另外带格式。\n\n")
	row("类型", "内部 ID", "基于", "proto", "列的 SQL 类型", "格式")
	row("---", "---", "---", "---", "---", "---")
	for _, t := range kinds.All() {
		base, sql, pat := t.Base, t.CanonicalSQL(), t.Pattern
		if base == "" {
			base = "—"
		}
		if sql == "" {
			sql = "—"
		}
		if pat == "" {
			pat = "—"
		} else {
			pat = "`" + pat + "`"
		}
		row(t.Name, "`"+t.ID+"`", base, "`"+t.Proto+"`", "`"+sql+"`", pat)
	}

	w("\n## 输入的键\n\n%s(必填: 是 / 否;筛选: `列 单元`,见下;写入 / 键 / 乐观锁: 命令的输入,见「命令」)。约束:\n\n", code(InputKeys()))
	for _, f := range constraints.Forms() {
		w("- `%s`\n", f)
	}
	w("\n范围 / 长度 / 格式 用在列表上时是每个元素的约束;个数只能用于列表。\n")

	w("\n## 输出的键\n\n一列只写说明(字符串)时,类型和值来自数据来源的同名列。也可以写: %s\n", code(OutputKeys()))
	w("\n`来自: 列名` = 改名(API 的名字和数据的列名不同)。`筛选` 和 `每组取一条` 写数据的列名,`排序` 写 API 的名字(排序在输出之后)。计算 / 自定义 的输出不能改名(由 AI 的代码决定)。\n")

	w("\n## 关联(多对一查找)\n\n`关联:` 下面一项一个(按书写顺序执行),每项可以写: %s。核心的元件 `lookup`。\n\n", code(LookupKeys()))
	w("```yaml\n关联:\n  warehouse: { 表: warehouses, 条件: [warehouse_code = warehouse_code], 列: { warehouse_name: name, region_code: region_code } }\n  region:    { 表: regions, 条件: [region_code = region_code], 列: { region_name: name }, 找不到时: 丢弃 }\n```\n\n")
	w("- `条件`: `当前行的列 = 对方的列`,多列的键写多项。对方的列必须构成对方的表的**主键或唯一约束**(最多一行匹配;不是 → 编译失败)。任一边为空 → 找不到\n")
	w("- `列`: `{ 新列名: 对方的列 }`(或 `[列, …]` = 同名)。加的列之后和数据来源的列一样: `输出`、`来自`、`筛选`、`固定条件`、`排序` 都可以用\n")
	w("- `找不到时`: `保留`(默认: 加的列为空,输出可以不设置)/ `丢弃`(这一行不要)\n")
	w("- 链式: 后面的关联可以用前面的关联加的列做条件。关联的表必须在同一个库里;分库的表只能关联同一个分库的表(条件里有两边的分库键相等)\n")
	w("- 对方可以是 存储: JSON版本 的逻辑表(R2.5): 对方 = 每个自然键最新的一行(删除 / 逻辑删除的键找不到,不会退回旧版本),唯一键 = 主键(自然键)。逻辑表 → 逻辑表的链也可以;嵌套 / 子聚合的子表同样\n")
	w("- 还不支持: 加的列是枚举\n")

	w("\n## 嵌套(一对多: 子行的列表)\n\n`嵌套:` 下面一项一个,每项可以写: %s。核心的元件 `nest`。名字 = 输出的列名(在 `输出` 里写说明),响应里是 repeated 的子行消息。\n\n", code(NestKeys()))
	w("```yaml\n嵌套:\n  items:\n    表: order_items\n    条件: [id = order_id]\n    固定条件: qty > 0          # 可以不写;子表的列\n    排序: [line_no 小到大]\n    上限: 50\n    列: [line_no, sku, qty, price]   # 或 { 新列名: 子表的列 }\n    行名: OrderItem            # 可以不写: 子表名的单数 PascalCase\n```\n\n")
	w("- `条件`: `当前行的列 = 子表的列`(多列写多项;任一边为空 → 不相等)。当前行的列可以是关联加的列\n")
	w("- `关联`(R2.6): 子行上的多对一查找,写法和数据来源的 `关联` 一样,条件的左边 = 子表的列(或前面的关联加的列;可以链式)。加的列之后和子表的列一样: `固定条件`、`排序`、`列` 都可以用(找不到时保留 → 加的列为空)。例: `关联: { warehouse: { 表: warehouses, 条件: [warehouse_code = warehouse_code], 列: { warehouse_name: name } } }`。子表 / 对方是逻辑表时还不支持\n")
	w("- `排序`: 子行的顺序必须是全序 —— 排序的列(加上 `条件` 里子表的列)要包含子表的主键或唯一键,否则编译失败\n")
	w("- `上限`: 子行多于上限 → **整个请求返回错误**(FAILED_PRECONDITION),不截断。没有子行 → 空列表 `[]`(不是空值)。例子里写 `结果: 超过上限`\n")
	w("- 值的表示和普通的列一样: 十进制是文本(不丢精度)、时间是 UTC、日期是 YYYY-MM-DD。只有一层(子行里不能再嵌套);子行的列不能是枚举\n")
	w("- 可以和 按键取一条 / 多条 / 一览 / 前N条 组合(分页作用在父行上;只检查响应里的行)。子表必须在同一个库里(分库: 条件里有两边的分库键相等)\n")

	w("\n## 子聚合(按父行聚合)\n\n`子聚合:` 下面一项一个(一项一个聚合),每项可以写: %s。核心的元件 `child_agg`;名字 = 加的列(之后和数据来源的列一样: 输出、筛选、排序)。\n\n", code(ChildAggKeys()))
	w("```yaml\n子聚合:\n  item_count:  { 表: order_items, 条件: [id = order_id], 计算: 件数 }\n  items_total: { 表: order_items, 条件: [id = order_id], 计算: 合计(amount) }\n  first_sku:   { 表: order_items, 条件: [id = order_id], 固定条件: qty > 1, 计算: 最小(sku) }\n```\n\n")
	w("| 计算 | 类型 | 没有子行 | 空值 |\n|---|---|---|---|\n")
	w("| `件数` | 整数64 | 0 | 数的是行数 |\n| `合计(列)` | 整数 → 整数64(溢出 → 查询失败);十进制 → 十进制(精确) | **0**(不是空值) | 忽略;全部为空 → 0 |\n")
	w("| `最小(列)` / `最大(列)` | 列的类型(文本按字节比较) | 空值(输出可以不设置) | 忽略;全部为空 → 空值 |\n\n")
	w("只有 件数 / 合计 / 最小 / 最大(和顶层的分组共用一套聚合: factory/core/agg.go)。合计里不能写表达式(数量 × 单价 请用数据库的生成列,例: storefront v2 的 order_items.amount)。\n")
	w("\n## 分组 / 排名\n\n%s 可以写(多条 / 前N条 / 一览)。筛选之后分组: 每组一行 = 分组键 + 计算的值;之后的 `输出` / `排序` 只能用分组键、计算、排名的输出名(不能写 `来自`)。\n\n", code(exits.GroupKeys))
	w("```yaml\n分组: { 键: [store_code], 计算: { total: 合计(amount), lines: 件数 } }\n排名: { 排序: [total 大到小], 输出: rank }\n排序: [rank 小到大, store_code 小到大]\n```\n\n")
	w("- 分组键为空的行是一组(不是每个空值一组)。没有输入行 → 没有输出行(不输出合计 0 的行)\n")
	w("- `排序` 必须包含全部分组键(不同的组的顺序要确定;前N条 / 一览 都依赖它)\n")
	w("- 排名 = SQL 的 RANK(): 排序的值相同 → 同名次,下一个名次跳过(1, 2, 2, 4)。只能和 分组 一起写\n")
	w("- **分组之后的筛选**(HAVING 一类): 输入的 `筛选` 写计算 / 排名的输出名 → 筛选放在分组 / 排名之后。例 `top_n: { 类型: 整数32, 必填: 是, 筛选: rank 小于等于 }` = 名次 N 以内(并列全部带出,结果可能多于 N 行);`筛选: total 大于等于` = 合计的下限(名次是筛选之前的全体里的名次)。分组键的筛选放在分组之前(结果一样)。输出名和表的列同名时分不清 → 报错(给计算改名)\n\n")
	row("计算", "内部名", "规则(factory/core/agg.go)")
	row("---", "---", "---")
	for _, a := range exits.AggWords {
		row(a.Word, "`"+a.Func+"`", a.Desc)
	}

	w("\n## 固定条件\n\n`固定条件:`(数据来源)和 嵌套 / 子聚合 的 `固定条件`: 不依赖输入的条件。写法: `条件 = 并且式 { 或者 并且式 }`;单项 = `不是 单项` / `(条件)` / `值 比较 值` / `列 为空` / `列 不为空`;比较 = `=` `<>` `<` `<=` `>` `>=`;值 = 列名 / 数字 / `'文本'`(日期也写成 `'2026-01-01'`)/ `今天` / `现在`。\n\n")
	w("```yaml\n固定条件: valid_from <= 今天 并且 (valid_to 为空 或者 valid_to >= 今天)   # 今天有效(结束日为空 = 无期限)\n```\n\n")
	w("- `今天` = 请求开始的时刻在领域的时区里的日期(和日期的列、整数编码的日期的列比较);`现在` = 请求开始的时刻(和时间的列比较)。和派生参数一样: 测试的时钟(X-Factory-Now)也适用,用到的 API 的 `例子` 要写 `现在`\n")
	w("- 列的类型要对得上: 日期的列 ↔ 今天,时间的列 ↔ 现在,否则编译失败。查询由 AI 写的 API(逃生口)不能用\n")
	w("\n## 筛选的单元\n\n输入的 `筛选: <列> <单元>`。定义是基本元件的组合(factory/core)。值没有指定时不筛选(必填时恒筛选)。列表的输入(属于): 不传和空列表都是「没有指定」(proto 分不出两者),不筛选;要求至少 1 个时写 `必填: 是` 或 `个数: \"1~N\"`。\n\n")
	row("单元", "内部名", "定义")
	row("---", "---", "---")
	names := lib.FilterNames()
	for _, n := range names {
		id, _ := lib.FilterID(n)
		row(n, "`"+id+"`", "`"+lib.Filters[n]+"`")
	}
	w("\n`前缀匹配` / `包含` 按字面匹配(`%%` `_` `\\` 不是通配符),按字节比较(大小写不同 = 不同)。**`包含` 用不上 btree 索引**(前面是通配符,大表会全表扫描,`make perf` 会警告):数据量大时建 pg_trgm 的 GIN 索引(`USING gin (列 gin_trgm_ops)`),或者改用 `前缀匹配`。\n")

	w("\n## 派生参数\n\n`派生参数:` 下面每个名字一个: 筛选的值由 `现在` 和输入计算,**不出现在请求里**。键: %s。\n\n", code(DerivedKeys()))
	w("```yaml\n派生参数:\n  stuck_before: { 计算: 现在 - stuck_minutes 分钟, 筛选: updated_at 小于 }\n  month_start:  { 计算: 月初(base_date - 1 个月), 筛选: sales_date 大于等于 }\n```\n\n")
	w("计算的写法(从左到右): `值 = 项 { (+ | -) 个数 单位 }`;项 = `现在` / `今天` / 日期·时间的输入 / `月初(值)` / `日初(值)` / `(值)`;")
	w("个数 = 整数 / 整数的输入;单位 = %s。\n\n", code(sortedKeys(derivedUnits)))
	w("- `现在` = 请求开始的时刻(服务器的时钟)。用到 `现在` 的 API,`例子` 要写 `现在: \"2026-11-01 09:00\"`(领域的时区;用例也可以各自写 `现在`)\n")
	w("- `今天` = `现在` 在领域的时区(`时区`)里的日期(日期,不是时间): 和日期的列、整数编码的日期的列比较(`今天 - days 天`)。时间的列请和 `日初(现在)` 这类时间比较。核心的元件 `local_date`\n")
	w("- 月的加减按 Postgres: 1/31 + 1 个月 = 2/28(闰年 2/29);日期只能加减天 / 月\n")
	w("- `月初` / `日初` = 截到那个月 / 那一天的开始;时间先换算到领域的时区(`时区`)。时间的天 / 月的加减也按领域的时区的日历\n")
	w("- 筛选只能是比较(%s);用在派生参数里的输入不能再写 `筛选`。输入不传(可选时)→ 值为空 → 不筛选\n", "等于 / 不等于 / 大于 / 大于等于 / 小于 / 小于等于")
	w("\n## 整数编码的日期(编码: YYYYMMDD)\n\n旧的表结构里日期常存成整数(20260131)。领域的列写 `列: { snap_ymd: { 说明: …, 编码: YYYYMMDD } }`(整数的列),输入写 `编码: YYYYMMDD`(整数的输入):\n\n")
	w("- 输入: 请求里仍是整数;不是合法的日期(20260230、20261301 …)→ 参数错误(proto 的 CEL)。在 `派生参数` 的计算里当作日期(`月初(base_ymd - 1 个月)`)\n")
	w("- 列: 和派生参数 / 日期的输入比较时按日期读;**不合法的值(20260230 …)永远不命中**(不按日历进位)。SQL 仍按整数比较(整数列上的索引能用)。输出、排序、每组取一条 仍是整数(合法的 YYYYMMDD 的整数顺序 = 日期的顺序)\n")
	w("- 核心的元件 `ymd`(整数 → 日期,不合法 → 空)\n")

	w("\n## 输入之间的规则\n\n`输入之间的规则:` 下面一行一条。\n\n")
	for _, f := range constraints.RelationForms() {
		w("- `%s`\n", f)
	}
	w("\n`不超过 N 天` 用于两个时间或两个日期。\n")
	return b.String(), nil
}

// commandReference: 命令(命令工厂,R3-1)的一节。
func commandReference(w func(string, ...any), row func(...string), code func([]string) string) {
	w("\n## 命令(命令工厂: 写入)\n\n")
	w("写一张表的一行。handler 全部由工厂生成(AI 不写): 校验 → 写操作作为数据 → 运行时的事务执行器在一个事务里执行(READ COMMITTED)→ 失败的原因 → 错误码。")
	w("`数据来源` = 写的表;`输出` = 写之后的行的列(新建 / 更新: 写之后的行;删除: 删除的行;不能改名)。\n\n")
	row("种类", "内部名", "做什么", "另外的键")
	row("---", "---", "---", "---")
	desc := map[string]string{
		"insert":  "插入一行,返回插入的行(含数据库生成的列: 默认值、序号)",
		"update":  "按主键更新 `写入` 的列和 `设置` 的列;有 `乐观锁` 时 `WHERE 版本 = 请求的值`,版本 + 1",
		"delete":  "按主键删除(物理删除;逻辑删除用 按键更新 + 设置 表达)",
		"command": "一个请求里按顺序执行的多个写操作(新建 / 幂等新建 / 更新 / 删除),一个事务;条件更新、幂等新建也写在这里(见下)",
	}
	for _, e := range exits.All() {
		if e.Command {
			row(e.Name, "`"+e.Kind+"`", desc[e.Kind], code(e.DesignKeys))
		}
	}
	w("\n```yaml\n种类: 按键更新\n数据来源: products\n输入:\n  sku:     { 类型: 文本,       必填: 是, 长度: 3~32, 格式: 代码, 键: sku }\n")
	w("  price:   { 类型: 非负十进制, 必填: 是, 写入: price }\n  version: { 类型: 整数32,     必填: 是, 范围: \"> 0\", 乐观锁: version }\n")
	w("设置: { updated_at: 现在 }\n找不到时: \"product not found: {sku}\"\n```\n\n")
	w("- 输入: 每个输入写 `写入: 列` / `键: 列` / `乐观锁: 列` 中的一个(不写 `筛选`)。`键` 必须正好是表的主键(按键更新 / 按键删除);新建的主键用 `写入`\n")
	w("- `乐观锁`: 整数的版本列,必填。版本号不一致 → `ABORTED`(⚖️ D1,待确认);行不存在 → `NOT_FOUND`(同一个事务里再读一次来区分)\n")
	w("- 按键更新 的 `写入` 必须是 必填(不传 = 不改 的部分更新还不支持);新建 的可以不传: 不传 = 不写这一列(数据库的默认值)\n")
	w("- `设置: { 列: 值 }`: 不来自请求的值。`现在` = 请求开始的时刻(时间的列;用到时 `例子` 要写 `现在`);枚举的列写值名(`DISCONTINUED`);其他写字面值\n")
	w("- `找不到时`: 行不存在时的消息(`{输入名}` 换成请求的值),按键更新 / 按键删除 必填\n")
	w("- 数据库的错误: 唯一约束 → `ALREADY_EXISTS`;CHECK / NOT NULL → `INVALID_ARGUMENT`(请求的校验漏了规则: 同时计入 `write_rejected_total`);外键 → `FAILED_PRECONDITION`;序列化失败 / 死锁 → 重试 3 次之后 `ABORTED`\n")
	w("- 输入的约束要覆盖表的 CHECK(例: `CHECK (sku ~ '^[A-Z0-9-]+$')` → `格式: 代码`,`CHECK (price >= 0)` → `非负十进制`): 不覆盖时自动生成的边界用例和状态差分测试会失败\n")
	w("- 还不支持: 部分更新(不传 = 不改)、批量写(R6)、写之后发事件、对列表逐项执行(R4)\n\n")
	w("例子的用例: `结果`(成功时的输出)或 `错误`(%s,或者直接写错误码)二选一,加上必填的 `之后`:\n\n", "`找不到` / `版本冲突` / `已存在` / `参数错误` / `前提不满足`")
	w("```yaml\n用例:\n  - 说明: 版本号一致 → 改价格,版本号加 1\n    输入: { sku: \"BEAN-001\", price: \"1300\", version: 3 }\n")
	w("    结果: { price: \"1300\", version: 4 }\n    之后:\n      products:\n        - { sku: \"BEAN-001\", price: 1300, version: 4 }\n")
	w("  - 说明: 版本号是旧的 → 版本冲突,什么都不写\n    输入: { sku: \"BEAN-001\", price: \"1300\", version: 2 }\n    错误: 版本冲突\n    之后: 不变\n```\n\n")
	w("- `之后: 不变` = 所有的表和请求之前一样;`之后: { 表: [行, …] }` = 这张表之后的**全部的行**(按主键对应,只比较写出来的列,主键必须写),没写出的表不变。`不设置` = 空值\n")
	w("- 每个用例都从 `准备数据` 的状态开始。另外工厂自动跑状态差分测试: 随机的初始状态 + 随机的请求序列(现有 / 不存在的键,对 / 错的版本号,新 / 已有的键),每个请求之后比较响应和表的完整状态(参考 = 内存里的模型状态)\n")
	compositeReference(w)
}

// compositeReference: 组合命令(R3-2)的一节。
func compositeReference(w func(string, ...any)) {
	w("\n### 组合命令(条件更新 / 幂等新建 / 多个写操作)\n\n")
	w("`种类: 组合命令`,不写 `数据来源`;`操作` 是按顺序执行的写操作的列表,全部在一个事务里(任何一个失败 → 全部回滚,返回那个操作的错误)。")
	w("输入只写类型和约束(不写 写入 / 键 / 乐观锁),操作里用 `输入.名字` 引用。\n\n")
	w("```yaml\n种类: 组合命令\n输入:\n  sku:    { 类型: 文本, 必填: 是, 长度: 3~32, 格式: 代码 }\n  delta:  { 类型: 整数32, 必填: 是, 范围: -100000~100000 }\n  reason: { 类型: AdjustmentReason, 必填: 是 }\n操作:\n")
	w("  - 库存:\n      更新: stock\n      键: { sku: 输入.sku }\n      设置: { available: \"available + 输入.delta\", version: \"version + 1\", updated_at: 现在 }\n")
	w("      条件: \"available + 输入.delta >= 0\"\n      不满足: INSUFFICIENT_STOCK\n      找不到时: \"stock not found: {sku}\"\n")
	w("  - 记录:\n      新建: stock_adjustments\n      值: { sku: 库存.sku, delta: 输入.delta, reason: 输入.reason, adjusted_at: 现在 }\n")
	w("输出:\n  available:     { 说明: 调整之后的可售数量, 来自: 库存.available }\n  adjustment_id: { 说明: 审计记录的 id, 来自: 记录.id }\n```\n\n")
	w("| 操作 | 写法 | 做什么 |\n|---|---|---|\n")
	w("| `新建` | `{ 新建: 表, 值: { 列: 值 } }` | 插入一行 |\n")
	w("| `幂等新建` | `{ 幂等新建: 表, 键: [列…], 值: { … } }` | 插入一行;`键`(表的主键或唯一约束,NOT NULL)已经有了 → 不写、不报错,返回已有的行。`操作名.新建` = 这次是不是真的插入了(输出用) |\n")
	w("| `更新` | `{ 更新: 表, 键: { 主键: 值 }, 设置: { 列: 值 }, 乐观锁?: { 版本列: 输入.version }, 条件?: \"…\", 不满足?: 原因码, 找不到时: \"…\" }` | 按主键更新。`条件` 不成立 → `FAILED_PRECONDITION`,消息以 `原因码:` 开头,并带 `google.rpc.ErrorInfo`(reason = 原因码) |\n")
	w("| `删除` | `{ 删除: 表, 键: { 主键: 值 }, 乐观锁?: …, 找不到时: \"…\" }` | 按主键删除 |\n\n")
	w("- 值和条件的写法: `输入.名字`、`操作名.列`(前面的操作的返回值,例: 新建返回的数据库生成的 id)、`列`(更新的这一行的列,值是更新之前的)、数字、`'文本'`、`现在`、枚举的值名;`+` / `-`;条件 = 比较(`=` `<>` `<` `<=` `>` `>=`),多个用 `并且`。空值: 运算 → 空,比较 → 不成立\n")
	w("- 更新没有碰到行时的判定顺序: 行不存在 → `NOT_FOUND`;版本号不一致 → `ABORTED`;条件不成立 → `FAILED_PRECONDITION` + 原因码\n")
	w("- 例子的 `错误:` 可以写原因码(`错误: INSUFFICIENT_STOCK`);`之后` 可以写多张表。数据库生成的序号在例子里是确定的(准备数据里的最大值 + 1)\n")
	w("- 组合命令的输入是必填;可以不传的输入只能直接写进 新建 / 幂等新建 的值(不传 = 不写这一列)\n")
	w("- 工厂另外自动跑: 状态差分(每个操作的成功和每种失败)、故障注入(第 k 个写操作之后失败 → 状态不变,每个 k)、并发(同一个请求同时 8 个: 成功次数 ≤ 串行执行的次数,状态 = 串行执行的状态;乐观锁的重读循环没有丢失的更新;幂等新建只有一行)、重放(只有幂等新建的命令: 发 3 次和 1 次相同)\n")
}
