var inputTypes = map[string][2]string{ // 中文类型 → proto 类型, 值的种类
	"整数32": {"int32", "int"}, "整数64": {"int64", "int"}, "文本": {"string", "string"},
	"时间": {"google.protobuf.Timestamp", "time"}, "布尔": {"bool", "bool"}, "小数": {"double", "float"},
	"日期": {"string", "date"}, "十进制": {"string", "decimal"}, // "YYYY-MM-DD" / 精确的十进制字符串(numeric 列用)
}

// proto 字符串里的写法(反斜杠要转义)
const (
	datePattern    = `^\\d{4}-\\d{2}-\\d{2}$`
	decimalPattern = `^-?\\d+(\\.\\d+)?$`
)

var columnTypes = map[string][2]string{
	"int2": {"int32", "int"}, "int4": {"int32", "int"}, "int8": {"int64", "int"},
	"text": {"string", "string"}, "varchar": {"string", "string"}, "bpchar": {"string", "string"},
	"bool": {"bool", "bool"}, "float8": {"double", "float"}, "float4": {"float", "float"},
	"timestamptz": {"google.protobuf.Timestamp", "time"}, "timestamp": {"google.protobuf.Timestamp", "time"},
	"date": {"string", "date"}, "numeric": {"string", "decimal"}, // "YYYY-MM-DD" / 十进制字符串(保持精度)
}

var filterOps = map[string]string{"等于": "eq", "大于": "gt", "大于等于": "gte", "小于": "lt", "小于等于": "lte", "前缀匹配": "prefix"}

func (c *ctx) column(table, col string) (compiler.Column, bool) {
	for _, x := range c.cat[table] {
		if x.Name == col {
			return x, true
		}
	}
	return compiler.Column{}, false
}

// typeOf: 中文类型名(或枚举名)→ proto 类型 + 值的种类
func (c *ctx) typeOf(t string) (string, string, bool) {
	if p, ok := inputTypes[t]; ok {
		return p[0], p[1], true
	}
	if c.d.Enum(t) != nil {
		return t, "enum:" + t, true
	}
	return "", "", false
}

// columnField: 输出字段的类型从数据来源的列推导(枚举看领域层)
func (c *ctx) columnField(table, col string) (string, string, bool, error) {
	cc, ok := c.column(table, col)
	if !ok {
		return "", "", false, fmt.Errorf("表 %s 没有列 %s", table, col)
	}
	if t := c.d.Tables[table]; t != nil {
		if en := t.ColEnum[col]; en != "" {
			return en, "enum:" + en, false, nil
		}
	}
	p, ok := columnTypes[cc.Type]
	if !ok {
		return "", "", false, fmt.Errorf("表 %s 的列 %s: 类型 %s 还不支持", table, col, cc.Type)
	}
	optional := !cc.NotNull && p[1] != "time" // Timestamp 本身就能表示"没有值"
	return p[0], p[1], optional, nil
}

var (
	reRange   = regexp.MustCompile(`^\s*(>=|<=|>|<)\s*(-?\d+)\s*$`)
	reBetween = regexp.MustCompile(`^\s*(-?\d+)\s*~\s*(-?\d+)\s*$`)
	reBefore  = regexp.MustCompile(`^(\w+)\s*早于\s*(\w+)$`)
	reWithin  = regexp.MustCompile(`^(\w+)\s*到\s*(\w+)\s*不超过\s*(\d+)\s*天$`)
)

func (c *ctx) inputField(a *API, in *Input, e *errs) *field {
	elemType, isList := strings.CutSuffix(in.Type, "列表")
	pt, kind, ok := c.typeOf(elemType)
	if !ok {
		e.add(in.Line, "输入 %s: 类型 %q 无法识别(整数32 / 整数64 / 文本 / 时间 / 布尔 / 小数 / 领域里定义的枚举名,后面加「列表」表示多个)", in.Name, in.Type)
		return nil
	}
	f := &field{Name: in.Name, Type: pt, Desc: in.Desc, kind: kind}
	if isList {
		f.Repeated = true
		if in.Required {
			f.Rules = append(f.Rules, "repeated.min_items = 1")
		}
		if in.Desc != "" && !in.Required {
			f.Desc = in.Desc + "(空列表 = 不按这个条件筛选)"
		}
		return f
	}
	scalarRule := map[string]string{"int32": "int32", "int64": "int64"}[pt]
	switch {
	case strings.HasPrefix(kind, "enum:"):
		f.Optional = !in.Required
		f.Rules = append(f.Rules, "enum = {defined_only: true, not_in: [0]}")
	case kind == "time":
		if in.Required {
			f.Rules = append(f.Rules, "required = true")
		}
	case kind == "date" || kind == "decimal":
		f.Optional = !in.Required
		pat := datePattern
		if kind == "decimal" {
			pat = decimalPattern
		}
		f.Rules = append(f.Rules, fmt.Sprintf("string.pattern = \"%s\"", pat))
	default:
		f.Optional = !in.Required
	}
	if in.Range != "" {
		if scalarRule == "" {
			e.add(in.Line, "输入 %s: 范围 只能用于整数", in.Name)
		} else if m := reRange.FindStringSubmatch(in.Range); m != nil {
			op := map[string]string{">": "gt", ">=": "gte", "<": "lt", "<=": "lte"}[m[1]]
			f.Rules = append(f.Rules, fmt.Sprintf("%s.%s = %s", scalarRule, op, m[2]))
		} else if m := reBetween.FindStringSubmatch(in.Range); m != nil {
			f.Rules = append(f.Rules, fmt.Sprintf("%s = {gte: %s, lte: %s}", scalarRule, m[1], m[2]))
		} else {
			e.add(in.Line, "输入 %s: 范围 %q 无法识别(例: \"> 0\", \"0~100\")", in.Name, in.Range)
		}
	}
	if in.Length != "" {
		if pt != "string" {
			e.add(in.Line, "输入 %s: 长度 只能用于文本", in.Name)
		} else if m := reBetween.FindStringSubmatch(in.Length); m != nil {
			f.Rules = append(f.Rules, fmt.Sprintf("string = {min_len: %s, max_len: %s}", m[1], m[2]))
		} else {
			e.add(in.Line, "输入 %s: 长度 %q 无法识别(例: \"1~64\")", in.Name, in.Length)
		}
	}
	return f
}

func (c *ctx) compileAPI(a *API) (*spec.Spec, string, error) {
	e := &errs{file: a.Path}
	table := a.Source
	if table != "" {
		if _, ok := c.cat[table]; !ok {
			e.add(1, "数据来源 %q 不是数据库里的表", table)
		}
	}

	// ---- 请求
	req := &message{Name: a.Name + "Request", Desc: a.Desc}
	if a.Kind == "list_keyset" {
		req.Fields = append(req.Fields,
			&field{Name: "page_size", Type: "int32", kind: "int", Desc: fmt.Sprintf("每页件数。0 = 默认 %d,最多 %d", a.PageDefault, a.PageMax),
				Rules: []string{fmt.Sprintf("int32 = {gte: 0, lte: %d}", a.PageMax)}},
			&field{Name: "page_token", Type: "string", kind: "string", Desc: "上一页返回的 next_page_token(不透明的字符串)"})
	}
	filters := map[string]spec.Filter{}
	for _, in := range a.Inputs {
		if f := c.inputField(a, in, e); f != nil {
			req.Fields = append(req.Fields, f)
		}
		if in.Filter != "" {
			parts := strings.Fields(in.Filter)
			op, ok := "", false
			if len(parts) == 2 {
				op, ok = filterOps[parts[1]]
				if !ok && c.lib.HasFilter(parts[1]) { // 单元库里的筛选单元: 直接用单元名
					op, ok = parts[1], true
				}
			}
			if !ok {
				e.add(in.Line, "输入 %s: 筛选 %q 无法识别。写成 \"列 <筛选单元>\",单元库里有: %s", in.Name, in.Filter, strings.Join(c.lib.FilterNames(), " / "))
				continue
			}
			cols := strings.Split(parts[0], "~") // 多列的单元: 开始列~结束列
			for _, col := range cols {
				if _, has := c.column(table, col); !has {
					e.add(in.Line, "输入 %s: 筛选的列 %s 不在表 %s 里", in.Name, col, table)
				}
			}
			sf := spec.Filter{Column: cols[0], Op: op}
			if len(cols) > 1 {
				sf.Columns = cols
			}
			filters[in.Name] = sf
		}
	}
	for i, r := range a.InputRules {
		x, err := c.celRule(req, r)
		if err != nil {
			e.add(1, "输入之间的规则 %q: %v", r, err)
			continue
		}
		x.ID = fmt.Sprintf("rule_%d", i+1)
		req.CEL = append(req.CEL, x)
	}

	// ---- 响应
	resp := &message{Name: a.Name + "Response", Desc: a.Desc}
	outFields := func(src string) []*field {
		var out []*field
		for _, o := range a.Outputs {
			f := &field{Name: o.Name, Desc: o.Desc}
			if o.From != "" && o.From != o.Name {
				e.add(o.Line, "输出 %s: 来自 和名字不同的列还不支持", o.Name)
			}
			if o.Type != "" {
				pt, kind, ok := c.typeOf(o.Type)
				if !ok {
					e.add(o.Line, "输出 %s: 类型 %q 无法识别", o.Name, o.Type)
					continue
				}
				f.Type, f.kind, f.Optional = pt, kind, o.Optional && kind != "time"
			} else {
				if src == "" {
					e.add(o.Line, "输出 %s: 计算的输出必须写 类型", o.Name)
					continue
				}
				pt, kind, opt, err := c.columnField(src, o.Name)
				if err != nil {
					e.add(o.Line, "输出 %s: %v(没有同名列时请写 类型)", o.Name, err)
					continue
				}
				f.Type, f.kind, f.Optional = pt, kind, opt
			}
			out = append(out, f)
		}
		return out
	}
	itemKey := ""
	switch a.Kind {
	case "list_keyset", "list_all":
		itemName := a.ItemName
		if itemName == "" {
			itemName = pascal(singular(table))
		}
		listField := a.ListField
		if listField == "" {
			listField = table
		}
		item := &message{Name: itemName, Fields: outFields(table)}
		if t := c.d.Tables[table]; t != nil {
			item.Desc = t.Desc
		}
		if prev, ok := c.msgByNm[item.Name]; ok {
			if !sameFields(prev, item) {
				e.add(1, "输出行 %s 已经被别的一览用过,但字段不同(请用 输出行名 改名)", item.Name)
			}
		} else {
			c.addMessage(item)
		}
		resp.Fields = []*field{{Name: listField, Type: item.Name, Repeated: true, kind: "message:" + item.Name}}
		if a.Kind == "list_keyset" {
			resp.Fields = append(resp.Fields, &field{Name: "next_page_token", Type: "string", kind: "string", Desc: "还有下一页时不为空"})
		} else {
			resp.Fields[0].Desc = fmt.Sprintf("最多 %d 件;超过时返回错误(不会截断)", a.MaxRows)
		}
		itemKey = a.OrderBy[len(a.OrderBy)-1]
	case "get_by_id":
		resp.Fields = outFields(table)
	default:
		resp.Fields = outFields("")
	}
	if err := e.err(); err != nil {
		return nil, "", err
	}
	c.addMessage(req)
	c.addMessage(resp)

	// ---- 机器用的式样书
	s := &spec.Spec{SpecVersion: spec.Version}
	s.API = spec.API{RPC: c.pkg + "." + c.service + "/" + a.Name, Owner: a.Owner, RiskLevel: a.Risk, Description: a.Background}
	s.Pattern = spec.Pattern{Kind: a.Kind, NotFoundMessage: a.NotFound}
	if a.Kind == "list_keyset" || a.Kind == "list_all" {
		dir := "asc"
		if a.Desc_ {
			dir = "desc"
		}
		s.Pattern.OrderBy, s.Pattern.Direction = a.OrderBy, dir
		if a.Kind == "list_keyset" {
			s.Pattern.PageSize = spec.PageSize{Default: a.PageDefault, Max: a.PageMax}
		} else {
			s.Pattern.MaxRows = a.MaxRows
		}
	}
	s.Datasource = spec.Datasource{Table: table, Filters: filters}
	if a.Kind == "compute" {
		s.Datasource.Columns = a.UseColumns
	}
	for _, r := range a.Rules {
		s.Behavior = append(s.Behavior, spec.Behavior{When: r.When, Then: r.Then})
	}
	for _, qa := range a.Reviewed {
		s.ReviewDecisions = append(s.ReviewDecisions, spec.ReviewDecision{Question: qa.Question, Decision: qa.Answer})
	}
	if err := c.examples(a, s, req, resp, itemKey); err != nil {
		return nil, "", err
	}
	return s, fmt.Sprintf("  // %s\n  rpc %s(%s) returns (%s);", oneLine(a.Desc), a.Name, req.Name, resp.Name), nil
}

func (c *ctx) celRule(req *message, r string) (cel, error) {
	has := func(name string) (*field, error) {
		for _, f := range req.Fields {
			if f.Name == name {
				return f, nil
			}
		}
		return nil, fmt.Errorf("%s 不是输入", name)
	}
	guard := func(fs ...*field) string {
		var g []string
		for _, f := range fs {
			required := false
			for _, rule := range f.Rules {
				if rule == "required = true" {
					required = true
				}
			}
			if !required && (f.kind == "time" || f.Optional) {
				g = append(g, fmt.Sprintf("!has(this.%s)", f.Name))
			}
		}
		if len(g) == 0 {
			return ""
		}
		return strings.Join(g, " || ") + " || "
	}
	if m := reBefore.FindStringSubmatch(r); m != nil {
		a, err := has(m[1])
		if err != nil {
			return cel{}, err
		}
		b, err := has(m[2])
		if err != nil {
			return cel{}, err
		}
		return cel{Message: fmt.Sprintf("%s must be earlier than %s", a.Name, b.Name), Expr: fmt.Sprintf("%sthis.%s < this.%s", guard(a, b), a.Name, b.Name)}, nil
	}
	if m := reWithin.FindStringSubmatch(r); m != nil {
		a, err := has(m[1])
		if err != nil {
			return cel{}, err
		}
		b, err := has(m[2])
		if err != nil {
			return cel{}, err
		}
		var days int
		fmt.Sscan(m[3], &days)
		return cel{Message: fmt.Sprintf("%s to %s must be %d days or less", a.Name, b.Name, days),
			Expr: fmt.Sprintf("%sthis.%s - this.%s <= duration('%dh')", guard(a, b), b.Name, a.Name, days*24)}, nil
	}
	return cel{}, fmt.Errorf("无法识别。目前支持: \"A 早于 B\" / \"A 到 B 不超过 N 天\"")
}

func (c *ctx) addMessage(m *message) {
	c.msgs = append(c.msgs, m)
	c.msgByNm[m.Name] = m
}

func sameFields(a, b *message) bool {
	if len(a.Fields) != len(b.Fields) {
		return false
	}
	for i := range a.Fields {
		if a.Fields[i].Name != b.Fields[i].Name || a.Fields[i].Type != b.Fields[i].Type {
			return false
		}
	}
	return true
}

