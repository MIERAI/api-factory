// Package design 是设计编译器: 中文式样书(design/<领域>/)→ 机器用的 proto + spec.yaml + _domain.yaml。
//
// 确定性的一对一翻译,不猜: 写不清楚的地方直接报错(中文,带文件和行号)。
// 人批准的是中文式样书,所以这里绝不能"理解"自由文本——说明、业务规则只原样带下去。
