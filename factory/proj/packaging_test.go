func TestPackagingFromGoMod(t *testing.T) {
	gomod := "module github.com/x/shop/services/catalog\n\ngo 1.27.4\n\nrequire github.com/MIERAI/api-factory-runtime v0.4.1\n"
	a, err := Packaging(gomod)
	if err != nil {
		t.Fatal(err)
	}
	b, _ := Packaging(gomod)
	for _, f := range PackagingFiles {
		if a[f] == "" || a[f] != b[f] {
			t.Fatalf("%s: missing or not deterministic", f)
		}
		if !strings.HasPrefix(a[f], "# Code generated by factory. DO NOT EDIT.") {
			t.Fatalf("%s: no generated header (factory stats counts it as generated by that marker)", f)
		}
	}
	if len(a) != len(PackagingFiles) {
		t.Fatalf("files = %d, PackagingFiles = %v", len(a), PackagingFiles)
	}
	d := a["Dockerfile"]
	for _, want := range []string{
		"ARG IMAGE_MIRROR=mirror.gcr.io/library\nFROM ${IMAGE_MIRROR}/golang:1.27.4-alpine AS build", // the Go of go.mod, via the mirror
		"go build -trimpath -ldflags \"-s -w\" -o /out/server ./cmd/server",
		"FROM gcr.io/distroless/static-debian12:nonroot",
		"USER nonroot:nonroot",
		"ENV SERVICE_NAME=catalog", // the module's last segment
		"ENV PORT=8080 METRICS_PORT=9090",
		"EXPOSE 8080 9090",
		`HEALTHCHECK --interval=10s --timeout=3s --start-period=60s --start-interval=1s --retries=3 CMD ["/server", "probe"]`,
	} {
		if !strings.Contains(d, want) {
			t.Fatalf("Dockerfile lacks %q:\n%s", want, d)
		}
	}
	// the context holds what the Dockerfile copies, nothing else (design/, specs/, db/, tests stay out)
	for _, want := range []string{"*\n", "!go.mod", "!go.sum", "!cmd/", "!gen/", "!internal/", "**/*_test.go"} {
		if !strings.Contains(a[".dockerignore"], want) {
			t.Fatalf(".dockerignore lacks %q", want)
		}
	}
	for _, copied := range []string{"COPY cmd", "COPY gen", "COPY internal"} {
		if !strings.Contains(d, copied) {
			t.Fatalf("Dockerfile lacks %q", copied)
		}
	}
}

func TestPackagingToolchainWins(t *testing.T) {
	a, err := Packaging("module m/x\n\ngo 1.27\n\ntoolchain go1.27.4\n")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(a["Dockerfile"], "/golang:1.27.4-alpine AS build") {
		t.Fatal("the toolchain line picks the build Go (as the go command does)")
	}
	a, _ = Packaging("module m/x\n\ngo 1.27\n")
	if !strings.Contains(a["Dockerfile"], "/golang:1.27-alpine AS build") {
		t.Fatal("go 1.27 → golang:1.27-alpine")
	}
	for _, bad := range []string{"go 1.27\n", "module m/x\n", "module m/x\ngo 1.28rc1\n"} {
		if _, err := Packaging(bad); err == nil {
			t.Fatalf("%q: want an error", bad)
		}
	}
}

func TestWritePackaging(t *testing.T) {
	dir := t.TempDir()
	os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module m/svc\n\ngo 1.27.4\n"), 0o644)
	if err := WritePackaging(dir); err != nil {
		t.Fatal(err)
	}
	want, _ := Packaging("module m/svc\n\ngo 1.27.4\n")
	for _, f := range PackagingFiles {
		b, err := os.ReadFile(filepath.Join(dir, f))
		if err != nil || string(b) != want[f] {
			t.Fatalf("%s: %v", f, err)
		}
	}
}

// Every example project carries the packaging its go.mod gives (scripts/projects.sh regenerates and diffs too; this
// catches it in go test).
func TestExamplesCarryPackaging(t *testing.T) {
	mods, _ := filepath.Glob("../../examples/*/*/go.mod")
	more, _ := filepath.Glob("../../examples/*/go.mod")
	mods = append(mods, more...)
	if len(mods) == 0 {
		t.Skip("no example projects")
	}
	for _, m := range mods {
		gomod, _ := os.ReadFile(m)
		want, err := Packaging(string(gomod))
		if err != nil {
			t.Fatalf("%s: %v", m, err)
		}
		for _, f := range PackagingFiles {
			got, err := os.ReadFile(filepath.Join(filepath.Dir(m), f))
			if err != nil || string(got) != want[f] {
				t.Errorf("%s/%s is not what the packaging template gives (factory --project DIR prepare)", filepath.Dir(m), f)
			}
		}
	}
}
