// 项目 README 里的环境变量表(GAPS G22): 服务读哪些环境变量,从运行时的清单(server.Env;运行时的测试检查它和源码一致)
// 加上这个项目用到的东西(有没有消息 / 状态机 / 分库的表)生成,不手抄。README 是项目的文件(init 写一次),
// 工厂只重写标记之间的一节(factory --project . prepare;没有标记就加在末尾)。

// Uses: 这个项目用到的、影响环境变量的东西(从 IR 推出来)。
type Uses struct {
	Messaging bool // 发出消息 / 消息处理器 / 状态机 → AMQP_URL 必须设置
	Machines  bool // 状态机 → 没有 AMQP_URL 超时也不扫描
	Shards    bool // 有分库的表 → FACTORY_SHARDS
}

const (
	envBegin = "<!-- factory:env:begin — generated by `factory --project . prepare` from the runtime's server.Env; do not edit -->"
	envEnd   = "<!-- factory:env:end -->"
)

// EnvSection: README 的那一节(含标记)。同样的 Uses 永远得到同样的字节。
func EnvSection(u Uses) string {
	var b strings.Builder
	b.WriteString(envBegin + "\n## Environment\n\n")
	b.WriteString("What the service reads at start-up (`runtime/server`). The image already sets `PORT`, `METRICS_PORT`, " +
		"`SERVICE_NAME` and `APP_VERSION`; the deployment provides the rest.\n\n")
	b.WriteString("| Variable | This service | Default | |\n|---|---|---|---|\n")
	var tests []server.EnvVar
	for _, e := range server.Env {
		need := ""
		switch e.When {
		case server.EnvTest:
			tests = append(tests, e)
			continue
		case server.EnvRequired:
			need = "**required**"
		case server.EnvMessaging:
			need = "not used (no messages)"
			if u.Messaging {
				need = "**required** (sends / handles messages)"
				if u.Machines {
					need = "**required** (sends / handles messages, state machine timeouts)"
				}
			}
		default:
			need = "optional"
			if e.Name == "FACTORY_SHARDS" && u.Shards {
				need = "set it (sharded tables)"
			}
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", e.Name, need, orDash(e.Default), cell(e.Desc))
	}
	if len(tests) > 0 {
		b.WriteString("\nTest environments only (never set them in production):\n\n")
		for _, e := range tests {
			fmt.Fprintf(&b, "- `%s`: %s\n", e.Name, e.Desc)
		}
	}
	b.WriteString(envEnd + "\n")
	return b.String()
}

func orDash(s string) string {
	if s == "" {
		return "—"
	}
	return "`" + s + "`"
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// WithEnvSection: README 的内容 → 换掉(或加上)环境变量的一节。
func WithEnvSection(readme string, u Uses) (string, error) {
	sec := EnvSection(u)
	i := strings.Index(readme, envBegin)
	if i < 0 {
		if strings.Contains(readme, envEnd) {
			return "", errors.New("README.md: " + envEnd + " without the begin marker")
		}
		if readme != "" && !strings.HasSuffix(readme, "\n") {
			readme += "\n"
		}
		if readme != "" {
			readme += "\n"
		}
		return readme + sec, nil
	}
	j := strings.Index(readme[i:], envEnd)
	if j < 0 {
		return "", errors.New("README.md: the environment section has no end marker " + envEnd)
	}
	rest := readme[i+j+len(envEnd):]
	rest = strings.TrimPrefix(rest, "\n")
	return readme[:i] + sec + rest, nil
}

// WriteEnvDoc: dir/README.md 的环境变量一节(没有 README 就新建一个只有这一节的)。
func WriteEnvDoc(dir string, u Uses) error {
	path := filepath.Join(dir, "README.md")
	b, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	out, err := WithEnvSection(string(b), u)
	if err != nil {
		return err
	}
	if out == string(b) {
		return nil
	}
	return os.WriteFile(path, []byte(out), 0o644)
}
