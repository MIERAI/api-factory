package proj

import (
	"fmt"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sort"
)

// 打包模板(boundaries.md §8.1: Dockerfile、健康检查、指标端口属于工厂): 每个项目都一样,只从 go.mod 推出来
// (Go 版本、模块名 → 服务名),所以是确定的生成物 —— factory init 写一次,factory --project DIR prepare 每次重写
// (项目改了 go.mod 的 Go 版本,Dockerfile 跟着变;scripts/projects.sh 的"重新生成不改变任何东西"会发现手改)。
//
// 做法和工厂仓库自己的 Dockerfile(release.yml 用 gitops-platform-blueprint 的 build-image 构建)一样: 多阶段,
// golang:<go.mod 的版本>-alpine 里编译 cmd/server,最终镜像 distroless static nonroot,只放服务器一个文件。
// 项目的服务器运行时不读任何文件(建表 db/schema 由平台在部署前执行;没有 migrate 步骤),所以只复制二进制。
//
// 健康检查和指标由运行时(api-factory-runtime/server)提供,镜像只把端口定下来:
//   PORT=8080          API + /livez(liveness) /readyz(readiness,停机开始后 503) /healthz(数据库能 ping 通)
//   METRICS_PORT=9090  /metrics(不认证的内部端口,Prometheus 从这里抓)
// k8s 清单不在这里(平台层)。

// PackagingFiles: 打包模板生成的文件(项目根目录的相对路径)。
var PackagingFiles = []string{"Dockerfile", ".dockerignore"}

const generatedHeader = "# Code generated by factory. DO NOT EDIT. (factory --project . prepare rewrites it from go.mod)\n"

var (
	goLine        = regexp.MustCompile(`(?m)^go\s+(\S+)`)
	toolchainLine = regexp.MustCompile(`(?m)^toolchain\s+go(\S+)`)
)

// Packaging: go.mod 的内容 → 打包模板的文件(路径 → 内容)。同样的 go.mod 永远得到同样的字节。
func Packaging(gomod string) (map[string]string, error) {
	m := moduleLine.FindStringSubmatch(gomod)
	if m == nil {
		return nil, fmt.Errorf("go.mod: no module line")
	}
	// 编译用的 Go: toolchain 行(有的话)优先,否则 go 行 —— 和 go 命令自己选工具链的规则一样
	var goVersion string
	if t := toolchainLine.FindStringSubmatch(gomod); t != nil {
		goVersion = t[1]
	} else if g := goLine.FindStringSubmatch(gomod); g != nil {
		goVersion = g[1]
	} else {
		return nil, fmt.Errorf("go.mod: no go line (the build image is golang:<go version>-alpine)")
	}
	if !regexp.MustCompile(`^[0-9]+(\.[0-9]+){1,2}$`).MatchString(goVersion) {
		return nil, fmt.Errorf("go.mod: go version %q is not a released version (golang:<version>-alpine)", goVersion)
	}
	service := path.Base(m[1])
	return map[string]string{
		"Dockerfile":    fmt.Sprintf(dockerfile, goVersion, service),
		".dockerignore": dockerignore,
	}, nil
}

// WritePackaging: dir(项目根目录)的 go.mod → 打包模板的文件写到 dir。
func WritePackaging(dir string) error {
	gomod, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err != nil {
		return err
	}
	files, err := Packaging(string(gomod))
	if err != nil {
		return err
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		if err := os.WriteFile(filepath.Join(dir, n), []byte(files[n]), 0o644); err != nil {
			return err
		}
	}
	return nil
}

const dockerfile = generatedHeader + `# The service's image: docker build -t <image> .   (run: DATABASE_URL and AUTH_MODE come from the deployment)
# A service that sends or handles messages (R4) also needs AMQP_URL: without it the outbox is written but never sent
FROM golang:%[1]s-alpine AS build
WORKDIR /src
COPY go.mod go.sum ./
RUN --mount=type=cache,target=/go/pkg/mod go mod download
COPY cmd ./cmd
COPY gen ./gen
COPY internal ./internal
RUN --mount=type=cache,target=/go/pkg/mod --mount=type=cache,target=/root/.cache/go-build \
    CGO_ENABLED=0 go build -trimpath -ldflags "-s -w" -o /out/server ./cmd/server

FROM gcr.io/distroless/static-debian12:nonroot
ARG VERSION=dev
COPY --from=build /out/server /server
# /healthz answers with X-App-Version: which build is serving after a deploy
ENV APP_VERSION=${VERSION}
ENV SERVICE_NAME=%[2]s
# PORT: the API and the probes /livez (liveness) /readyz (readiness) /healthz (database reachable)
# METRICS_PORT: /metrics without authentication, for Prometheus only (not exposed outside the cluster)
ENV PORT=8080 METRICS_PORT=9090
EXPOSE 8080 9090
USER nonroot:nonroot
ENTRYPOINT ["/server"]
`

// 构建上下文只要编译用的东西(Dockerfile 只复制 go.mod / go.sum / cmd / gen / internal)。
const dockerignore = generatedHeader + `*
!go.mod
!go.sum
!cmd/
!gen/
!internal/
**/*_test.go
`
