-- 平台管理的 DB 结构(人工维护,AI 不可修改)
-- 任务的执行(写接口的样例: 命令工厂 R3-2 的组合命令 / 条件更新 / 幂等新建)

-- 每个任务类型剩下的执行额度(条件更新: 够才扣)
CREATE TABLE IF NOT EXISTS job_quotas (
    job_type   TEXT        PRIMARY KEY CHECK (length(job_type) BETWEEN 1 AND 64),
    remaining  INTEGER     NOT NULL CHECK (remaining >= 0),        -- 不会小于 0: 不超额执行
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 任务的一次执行(id 由数据库生成)
CREATE TABLE IF NOT EXISTS job_runs (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type   TEXT        NOT NULL REFERENCES job_quotas (job_type),
    status     INTEGER     NOT NULL DEFAULT 1 CHECK (status IN (1, 2, 3)),   -- 1 执行中 2 完成 3 失败
    started_at TIMESTAMPTZ NOT NULL
);

-- 执行的日志(第一条在开始执行时写)
CREATE TABLE IF NOT EXISTS job_run_logs (
    id        BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id    BIGINT      NOT NULL REFERENCES job_runs (id),
    message   TEXT        NOT NULL CHECK (length(message) BETWEEN 1 AND 200),
    logged_at TIMESTAMPTZ NOT NULL
);

-- 任务的执行请求(调用方带请求 id: 重复提交同一个请求只登记一次)
CREATE TABLE IF NOT EXISTS job_requests (
    request_id  TEXT        PRIMARY KEY CHECK (request_id ~ '^[A-Z0-9-]{8,64}$'),
    job_type    TEXT        NOT NULL CHECK (length(job_type) BETWEEN 1 AND 64),
    priority    INTEGER     NOT NULL CHECK (priority BETWEEN 1 AND 9),
    received_at TIMESTAMPTZ NOT NULL
);
