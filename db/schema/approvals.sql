-- 平台管理的 DB 结构(人工维护,AI 不可修改)
-- 文档的审批(状态机 R5 的中立样例: 初始转移、两个等待状态、守卫、超时重发 / 期限、载入的子行)

-- 提交审批的文档。状态机 DocumentReview 的状态在这一行上: status / entered_at(进入当前状态的时间,超时的基准)/
-- version(每次转移 / 重发 + 1)/ attempts(当前状态的命令重发了几次)
CREATE TABLE IF NOT EXISTS documents (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        TEXT        NOT NULL CHECK (length(title) BETWEEN 1 AND 100),
    revision     INTEGER     NOT NULL DEFAULT 1 CHECK (revision BETWEEN 1 AND 1000),
    status       INTEGER     NOT NULL CHECK (status IN (1, 2, 3, 4, 5)),   -- 1 审批中 2 发布中 3 已发布 4 驳回 5 过期
    version      INTEGER     NOT NULL DEFAULT 1 CHECK (version > 0),
    attempts     INTEGER     NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    submitted_at TIMESTAMPTZ NOT NULL,
    entered_at   TIMESTAMPTZ NOT NULL
);
-- 超时扫描: 等待状态的文档,进入早的在前
CREATE INDEX IF NOT EXISTS documents_waiting_idx ON documents (status, entered_at) WHERE status IN (1, 2);

-- 一个文档的评审人(票数 = 这个评审人的意见的权重)
CREATE TABLE IF NOT EXISTS document_reviewers (
    doc_id   BIGINT  NOT NULL REFERENCES documents (id),
    reviewer TEXT    NOT NULL CHECK (length(reviewer) BETWEEN 2 AND 32),
    weight   INTEGER NOT NULL CHECK (weight BETWEEN 1 AND 5),
    PRIMARY KEY (doc_id, reviewer)
);
