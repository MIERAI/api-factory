#!/usr/bin/env bash
# 审查收敛的实测(P5): 对一批中文式样书反复"审查 → 按推荐的选项回答 → 重新生成",直到通过,统计轮数。
# 按推荐回答 = 模拟设计者(真实的设计者可能选别的,但轮数的性质一样)。
#   usage: scripts/review-converge.sh [--max N] [--jobs J] design/<领域>/<API>.yaml ...
#   结果: factory review-stats(标签 converge)
# 各 API 按轮同步: 同一轮的审查并行跑,然后统一回答、统一重新生成(生成会改所有的 spec,不能并行)。
set -uo pipefail
MAX=5; JOBS=4
while [[ $# -gt 0 && $1 == --* ]]; do
  case $1 in --max) MAX=$2; shift 2;; --jobs) JOBS=$2; shift 2;; *) echo "unknown $1"; exit 2;; esac
done
[[ $# -gt 0 ]] || { echo "usage: $0 [--max N] [--jobs J] design/<领域>/<API>.yaml ..."; exit 2; }
export PATH=/opt/homebrew/bin:$PATH
go build -o .factory/factory ./factory/cmd/factory || exit 2
LOG=.factory/converge; mkdir -p $LOG

# 按推荐的选项回答: F1=<推荐+1> ...
PICK='
import json, sys
try:
    fs = json.load(sys.stdin)
except Exception:
    fs = []
print(" ".join("%s=%d" % (f["id"], int(f.get("recommended") or 0) + 1) for f in fs if f.get("options")))
'
spec_of() { # 设计稿 → 生成的 spec
  grep -l "^# Code generated by factory from $1\. DO NOT EDIT\.$" specs/*/*/spec.yaml | head -1
}
pending=("$@")
for ((round = 1; round <= MAX && ${#pending[@]} > 0; round++)); do
  echo "━━ 第 $round 轮: ${#pending[@]} 个 API"
  .factory/factory design >/dev/null && .factory/factory prepare >/dev/null || { echo "✗ 生成失败"; exit 2; }
  running=0
  for d in "${pending[@]}"; do
    s=$(spec_of "$d"); [[ -n $s ]] || { echo "✗ 找不到 $d 的 spec"; exit 2; }
    n=$(basename "$d" .yaml)
    ( scripts/review.sh "$s" "" converge > "$LOG/$n.r$round.txt" 2>&1; echo $? > "$LOG/$n.rc" ) &
    running=$((running + 1))
    if (( running >= JOBS )); then wait -n 2>/dev/null || wait; running=$((running - 1)); fi
  done
  wait
  next=()
  for d in "${pending[@]}"; do
    n=$(basename "$d" .yaml); rc=$(cat "$LOG/$n.rc")
    summary=$(grep '⏱' "$LOG/$n.r$round.txt" | tail -1)
    case $rc in
      0) echo "  ✓ $n  $summary";;
      1) echo "  … $n  $summary"
         # 按推荐回答所有可以回答的问题(包括 minor 和迟到的问题: 记录下来,下一轮就不会再问)
         args=$(.factory/factory answer --list "$d" 2>/dev/null | python3 -c "$PICK")
         if [[ -n $args ]]; then
           # shellcheck disable=SC2086
           .factory/factory answer "$d" $args > /dev/null || echo "    ✗ 回答失败: $args"
         fi
         next+=("$d");;
      *) echo "  ✗ $n  审查工具出错(见 $LOG/$n.r$round.txt)";;
    esac
  done
  pending=("${next[@]+"${next[@]}"}")
done
for d in "${pending[@]+"${pending[@]}"}"; do echo "  ✗ $(basename "$d" .yaml): $MAX 轮还没通过"; done
.factory/factory review-stats --match -converge
