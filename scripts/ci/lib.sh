# CI 各阶段共用(GitHub Actions 和本地模拟 scripts/ci/sim.sh 跑的是同一套脚本)
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
export PATH="$PATH:$(go env GOPATH)/bin"
# 结果的 Markdown: 总是写文件(后面的步骤贴到 PR 上;GitHub 的 $GITHUB_STEP_SUMMARY 是每个步骤各自的文件,别的步骤读不到),
# 在 GitHub 上同时写步骤的摘要
SUMMARY=${CI_SUMMARY:-.factory/ci-summary.md}
mkdir -p .factory "$(dirname "$SUMMARY")"
md() {
  printf '%s\n' "$@" >> "$SUMMARY"
  if [[ -n ${GITHUB_STEP_SUMMARY:-} ]]; then printf '%s\n' "$@" >> "$GITHUB_STEP_SUMMARY"; fi
}

# 阶段计时: stage "名字" 命令...
stage() {
  local name=$1; shift
  local t0=$(date +%s) rc=0
  echo "━━ $name"
  "$@" || rc=$?
  local s=$(( $(date +%s) - t0 ))
  echo "   ⏱ ${s}s"
  if (( rc )); then md "| ✗ $name | ${s}s |"; else md "| $name | ${s}s |"; fi
  return $rc
}

# 这次改动的式样书(design/ 的变化 → 生成的 specs/<领域>/<api>/spec.yaml)。
# 领域.yaml 变了 = 这个领域的全部 API。BASE 之后改过的。
changed_specs() {
  local base=$1 f dom
  local files; files=$(git diff --name-only "$base" -- design/ 2>/dev/null || true)
  for f in $files; do
    dom=$(echo "$f" | cut -d/ -f2)
    case "$f" in
      */领域.yaml|*/领域.审查.yaml) ls specs/"$dom"/*/spec.yaml 2>/dev/null ;;
      *.审查.yaml) grep -l "^# Code generated by factory from ${f%.审查.yaml}.yaml" specs/"$dom"/*/spec.yaml 2>/dev/null || true ;;
      *.yaml) grep -l "^# Code generated by factory from $f" specs/"$dom"/*/spec.yaml 2>/dev/null || true ;;
    esac
  done | sort -u
}
