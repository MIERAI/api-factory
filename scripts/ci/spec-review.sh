#!/usr/bin/env bash
# 阶段 1: 式样书的 PR(改 design/,或项目的 <项目>/design/)。机械检查 → 确定性生成(不提交)→ AI 审查改动的 API。
#   有挡流水线的问题 → 失败(PR 上回答问题: factory answer design/…,再推)
#   BASE: 和哪个提交比(GitHub: origin/main)。REVIEW=skip: 不调用 AI(本地模拟 / 没有 AI 凭证时)
#   REVIEW_MODEL: factory.yaml 的模型(空 = 默认 claude)。claude* 以外 = 只作参考: 意见贴出来,不挡 PR
#   (实测: 本地模型的 blocker 全是误报,审查后面没有闸门兜底)
#   PROJECTS: 要审查的项目(空格隔开;默认 scripts/projects.sh --list = examples/ 下有 factory.yaml 的目录)。
#   每个项目和本仓库一样: 生成 → review-changed(项目自己的 design/ 和 BASE 比)→ 审查;结果在 <项目>/.factory/reviews,
#   回答写进 <项目>/design/<领域>/X.审查.yaml(factory answer <项目>/design/<领域>/X.yaml)
source "$(dirname "$0")/lib.sh"
BASE=${BASE:-origin/main}
md "## 式样书检查" "" "| 步骤 | 时间 |" "|---|---|"
stage "① 式样书闸门(机械检查)" make --no-print-directory check
stage "② 确定性生成(只检查能不能生成)" make --no-print-directory prepare
projects=${PROJECTS-$(scripts/projects.sh --list)}
gen_project() { local f=(go run ./factory/cmd/factory --project "$1"); "${f[@]}" design >/dev/null && "${f[@]}" check >/dev/null && "${f[@]}" prepare >/dev/null; }
for p in $projects; do
  stage "②' $p: 式样书闸门 + 确定性生成" gen_project "$p"
done
# 要审查的 API = 审查的输入(设计书 + 审查记录 + 领域里它引用的部分)和 BASE 不同的。
# 领域.yaml 里加了一张无关的表 → 不审查(以前领域.yaml 一变,这个领域的全部 API 都重审;审查不确定,已经通过的设计书又被挡)
# F: 当前项目($p;. = 本仓库)的 factory
F() { if [[ $p == . ]]; then go run ./factory/cmd/factory "$@"; else go run ./factory/cmd/factory --project "$p" "$@"; fi; }
todo=()   # "<项目|.> <spec>"
for p in . $projects; do
  changed=$(F review-changed -v --base "$BASE")   # 失败 → 整个脚本失败(不能当成"没有改动")
  for s in $changed; do todo+=("$p $s"); done
done
md "" "改动的 API: ${#todo[@]} 个" ""
blocked=0
for item in "${todo[@]+"${todo[@]}"}"; do
  p=${item%% *}; s=${item#* }
  PROJECT=; [[ $p != . ]] && PROJECT=$p
  export PROJECT   # review-key.sh / review.sh
  id=$(F ai-paths "$s" | head -1)
  name=$id; [[ $p != . ]] && name="$p: $id"
  reviews=$p/.factory/reviews
  if [[ ${REVIEW:-} == skip ]]; then
    md "- \`$name\`: AI 审查跳过(REVIEW=skip)"
    continue
  fi
  # 审查的输入(式样书 / 设计书 / 审查记录 / 领域 / prompt / 模型)和上次通过时相同 → 沿用(审查是不确定的:
  # 同一个设计书再审一次可能翻转;.factory/reviews 在 CI 里按 PR 分支保留,见 spec-pr.yml)
  key=$(scripts/ci/review-key.sh "$s" "${REVIEW_MODEL:-default}")
  mark=$reviews/passed/$id-$key
  if [[ -f $mark ]]; then
    md "- \`$name\`: ✓ 审查通过(审查的输入没有变,沿用 $(cat "$mark") 的结果)"
    continue
  fi
  rc=0; out=$(scripts/review.sh "$s" "${REVIEW_MODEL:-}" 2>&1) || rc=$?
  if [[ $rc == 0 ]]; then mkdir -p "$reviews/passed"; date '+%Y-%m-%d %H:%M' > "$mark"; fi
  usage=$(scripts/ci/ai-usage.sh "$(ls -td "$reviews"/*-"${REVIEW_MODEL:-default}"-"$id" 2>/dev/null | head -1)/ai.json")
  src=$(head -1 "$p/$s" | sed -n 's/^# Code generated by factory from \(design\/.*\)\. DO NOT EDIT\.$/\1/p')
  answer="factory answer ${PROJECT:+$PROJECT/}${src:-<设计书>}"
  if [[ -n ${REVIEW_MODEL:-} && ${REVIEW_MODEL} != claude* ]]; then   # 只作参考
    case $rc in
      0) md "- \`$name\`: ✓ 审查通过($REVIEW_MODEL,参考)" ;;
      1) md "- \`$name\`: ⚠ $REVIEW_MODEL 的审查意见(仅供参考,不阻塞;本地模型误报多,由人判断)" "" '```' "$out" '```' ;;
      *) md "- \`$name\`: ⚠ 审查工具出错(不阻塞)" "" '```' "$out" '```' ;;
    esac
    md "  - $usage"
    continue
  fi
  case $rc in
    0) md "- \`$name\`: ✓ 审查通过" ;;
    1) md "- \`$name\`: ✗ 有要回答的问题(\`$answer F1=…\`)" "" '```' "$out" '```'; blocked=1 ;;
    *) md "- \`$name\`: ⚠ 审查工具出错(不是规格的问题)" "" '```' "$out" '```'; blocked=1 ;;
  esac
  md "  - $usage"
done
exit $blocked
