"""种类组合矩阵(P3): 生成覆盖 来源 × 分库 × 出口 × (筛选单元, 类型) × 必填/可选 的设计稿。

    python3 scripts/matrix.py <输出目录>    # 写 design/matrix/ 和 db/schema/matrix.sql

每对合法的 (筛选单元, 类型) 至少出现一次,必填 / 可选轮流;另有一个没有输入的 API。
人写的例子是"空表 → 空列表 / 找不到"(不和工厂的逻辑循环论证);真正的验证是差分测试。
"""
import itertools
import os
import sys

out = sys.argv[1]
os.makedirs(os.path.join(out, "design/matrix"), exist_ok=True)
os.makedirs(os.path.join(out, "db/schema"), exist_ok=True)

# 列: 名字 → (中文类型, SQL 类型, 可空)
COLS = {
    "i32": ("整数32", "INTEGER", False), "i64": ("整数64", "BIGINT", True), "txt": ("文本", "TEXT", True),
    "flag": ("布尔", "BOOLEAN", True), "amt": ("十进制", "NUMERIC", True), "day": ("日期", "DATE", True),
    "at": ("时间", "TIMESTAMPTZ", True), "zip": ("邮编", "TEXT", True), "vfrom": ("整数32", "INTEGER", False),
    "vto": ("整数32", "INTEGER", True), "store": ("整数32", "INTEGER", False),
}
# (筛选单元, 列, 输入类型)。有效期包含 用两列
PAIRS = [("等于", c, COLS[c][0]) for c in ["i32", "i64", "txt", "flag", "amt", "day", "at", "zip"]]
PAIRS += [("不等于", c, COLS[c][0]) for c in ["i32", "txt", "amt", "day"]]
PAIRS += [("大于等于", c, COLS[c][0]) for c in ["i32", "amt", "day", "at", "txt"]]
PAIRS += [("小于", c, COLS[c][0]) for c in ["i64", "amt", "day", "at", "zip"]]
PAIRS += [("前缀匹配", c, "文本") for c in ["txt", "zip"]]  # 前缀不是完整的值: 带格式的类型(邮编)的前缀用 文本
PAIRS += [("属于", c, COLS[c][0] + "列表") for c in ["i32", "i64", "txt", "amt", "day"]]
PAIRS += [("有效期包含", "vfrom~vto", "整数32")]

EXAMPLE = {"整数32": "1", "整数64": "1", "文本": '"a"', "布尔": "是", "十进制": '"1.5"', "日期": "2026-01-01",
           "时间": "2026-01-01 09:00", "邮编": '"100-0001"'}

TABLES = [  # (逻辑表, JSON版本?, 分库?)
    ("mx_plain", False, False), ("mx_plain_sh", False, True),
    ("mx_ver", True, False), ("mx_ver_sh", True, True),
]
EXITS = ["按键取一条", "一览", "多条", "前N条"]

# ---- 表结构
sql = ["-- Code generated by scripts/matrix.py (种类组合矩阵). DO NOT EDIT."]
for t, ver, _ in TABLES:
    if ver:
        sql.append(f"""CREATE TABLE IF NOT EXISTS {t}_events (
    id BIGSERIAL PRIMARY KEY, data JSONB NOT NULL, action_type INTEGER NOT NULL DEFAULT 0,
    registered_by TEXT NOT NULL DEFAULT 'factory', registered_at TIMESTAMPTZ NOT NULL DEFAULT now());""")
    else:
        cols = ",\n    ".join(f"{c} {ty}{'' if null else ' NOT NULL'}" for c, (_, ty, null) in COLS.items())
        sql.append(f"CREATE TABLE IF NOT EXISTS {t} (\n    id BIGINT PRIMARY KEY,\n    {cols}\n);")
open(os.path.join(out, "db/schema/matrix.sql"), "w").write("\n\n".join(sql) + "\n")

# ---- 领域
dom = ["# Code generated by scripts/matrix.py (种类组合矩阵). DO NOT EDIT.", "领域: matrix", "说明: 种类组合矩阵", "时区: Asia/Tokyo", "", "表:"]
for t, ver, sh in TABLES:
    dom.append(f"  {t}:")
    dom.append(f"    说明: 矩阵 {t}")
    dom.append("    主键: [id]")
    if sh:
        dom.append("    分库: store")
    if ver:
        dom += ["    存储: JSON版本", f"    原始表: {t}_events", "    逻辑删除: deleted = 1", "    字段:",
                "      id: { 类型: 整数64, 说明: id }"]
        dom += [f"      {c}: {{ 类型: {cn}, 说明: {c} }}" for c, (cn, _, _) in COLS.items()]
    else:
        dom.append("    列:")
        dom.append("      id: id")
        dom += [f"      {c}: {c}" for c in COLS]
open(os.path.join(out, "design/matrix/领域.yaml"), "w").write("\n".join(dom) + "\n")

# ---- API
pairs = itertools.cycle(PAIRS)
n_api = 0
for (t, ver, sh), ex in itertools.product(TABLES, EXITS):
    n_api += 1
    name = f"Mx{n_api:02d}" + "".join(p.capitalize() for p in t.split("_"))
    inputs, req = [], {}
    if ex == "按键取一条":
        inputs.append(("id", "整数64", True, "id 等于"))
        req["id"] = "1"
    if sh:
        inputs.append(("store", "整数32", True, "store 等于"))
        req["store"] = "1"
    if ex != "按键取一条":
        for k in range(3):
            cell, col, typ = next(pairs)
            pname = f"p{k}_{col.replace('~', '_')}"
            required = (n_api + k) % 2 == 0
            inputs.append((pname, typ, required, f"{col} {cell}"))
            if required:
                base = typ.removesuffix("列表")
                req[pname] = f"[{EXAMPLE[base]}]" if typ.endswith("列表") else EXAMPLE[base]
    lines = [f"# Code generated by scripts/matrix.py (种类组合矩阵). DO NOT EDIT.", f"API: {name}",
             f"说明: 矩阵 {t} × {ex}", "背景: 种类组合矩阵(自动生成)", "负责人: matrix", "风险: 低", "",
             f"种类: {ex}", f"数据来源: {t}", "", "输入:" if inputs else "输入: {}"]
    for pname, typ, required, flt in inputs:
        lines.append(f"  {pname}: {{ 类型: {typ}, 必填: {'是' if required else '否'}, 说明: {pname}, 筛选: {flt} }}")
    lines += ["", "输出:", "  id: id"] + [f"  {c}: {c}" for c in COLS]
    lines.append("")
    item = f"{name}Row"
    if ex == "按键取一条":
        lines.append("找不到时: not found")
        result = "找不到"
    else:
        # 分页的排序列必须不为空: JSON版本 的字段除了主键都可能为空 → 只按主键
        lines.append("排序: [id 小到大]" if (ver and ex == "一览") else "排序: [i32 小到大, id 小到大]")
        lines.append({"一览": "分页: { 默认每页: 5, 每页最多: 50 }", "多条": "上限: 30", "前N条": "条数: 4"}[ex])
        lines.append(f"输出行名: {item}")
        result = f"{{ {t}: [] }}"
    req_s = ", ".join(f"{k}: {v}" for k, v in req.items())
    lines += ["", "例子:", "  准备数据:", f"    {t}: []", "  用例:", "    - 说明: 空表",
              f"      输入: {{ {req_s} }}", f"      结果: {result}"]
    open(os.path.join(out, f"design/matrix/{name}.yaml"), "w").write("\n".join(lines) + "\n")

# 没有输入的 API
lines = ["# Code generated by scripts/matrix.py (种类组合矩阵). DO NOT EDIT.", "API: MxNoInput", "说明: 矩阵 没有输入",
         "背景: 种类组合矩阵(自动生成)", "负责人: matrix", "风险: 低", "", "种类: 多条", "数据来源: mx_plain", "",
         "输入: {}", "", "输出:", "  id: id", "  txt: txt", "", "排序: [id 小到大]", "上限: 100", "输出行名: MxNoInputRow",
         "", "例子:", "  准备数据:", "    mx_plain: []", "  用例:", "    - 说明: 空表", "      输入: {}", "      结果: { mx_plain: [] }"]
open(os.path.join(out, "design/matrix/MxNoInput.yaml"), "w").write("\n".join(lines) + "\n")
# ---- 第二代: 枚举 / 复合主键 / 每组取一条 / 输入之间的规则
sql2 = """
CREATE TABLE IF NOT EXISTS mx_enum (
    id BIGINT PRIMARY KEY,
    kind INTEGER NOT NULL CHECK (kind IN (1, 2, 3)),
    day DATE,
    at TIMESTAMPTZ NOT NULL,
    i32 INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS mx_comp (
    grp INTEGER NOT NULL,
    seq INTEGER NOT NULL,
    txt TEXT,
    i32 INTEGER NOT NULL,
    PRIMARY KEY (grp, seq)
);
"""
open(os.path.join(out, "db/schema/matrix.sql"), "a").write(sql2)
dom2 = """
枚举:
  MxKind:
    说明: 矩阵的种类
    值:
      RED:   { 说明: 红, 数据库值: 1 }
      GREEN: { 说明: 绿, 数据库值: 2 }
      BLUE:  { 说明: 蓝, 数据库值: 3 }

表2:
  mx_enum:
    说明: 枚举的表
    主键: [id]
    列:
      id: id
      kind: { 说明: 种类, 枚举: MxKind }
      day: day
      at: at
      i32: i32
  mx_comp:
    说明: 复合主键的表
    主键: [grp, seq]
    列:
      grp: grp
      seq: seq
      txt: txt
      i32: i32
"""
d = open(os.path.join(out, "design/matrix/领域.yaml")).read()
enum_block, tables_block = dom2.split("\n表2:\n")
d = d.replace("\n表:\n", enum_block + "\n表:\n", 1) + tables_block
open(os.path.join(out, "design/matrix/领域.yaml"), "w").write(d)

def api(name, kind, table, inputs, outputs, extra, req, result, rules=()):
    lines = ["# Code generated by scripts/matrix.py (种类组合矩阵). DO NOT EDIT.", f"API: {name}", f"说明: 矩阵 {name}",
             "背景: 种类组合矩阵(自动生成)", "负责人: matrix", "风险: 低", "", f"种类: {kind}", f"数据来源: {table}", "", "输入:"]
    lines += [f"  {i}" for i in inputs]
    if rules:
        lines += ["", "输入之间的规则:"] + [f"  - {r}" for r in rules]
    lines += ["", "输出:"] + [f"  {o}: {o}" for o in outputs] + [""] + extra
    lines += ["", "例子:", "  准备数据:", f"    {table}: []", "  用例:", "    - 说明: 空表", f"      输入: {{ {req} }}", f"      结果: {result}"]
    open(os.path.join(out, f"design/matrix/{name}.yaml"), "w").write("\n".join(lines) + "\n")

api("MxEnumList", "一览", "mx_enum",
    ["kind: { 类型: MxKind, 必填: 否, 说明: 种类, 筛选: kind 等于 }",
     "day_from: { 类型: 日期, 必填: 否, 说明: 开始, 筛选: day 大于等于 }",
     "day_to: { 类型: 日期, 必填: 否, 说明: 结束, 筛选: day 小于 }"],
    ["id", "kind", "day", "at"], ["排序: [at 小到大, id 小到大]", "分页: { 默认每页: 5, 每页最多: 50 }", "输出行名: MxEnumRow"],
    "", "{ mx_enum: [] }", rules=("day_from 早于 day_to",))
api("MxEnumIn", "多条", "mx_enum",
    ["kinds: { 类型: MxKind列表, 必填: 是, 说明: 种类, 筛选: kind 属于 }",
     "at_after: { 类型: 时间, 必填: 否, 说明: 之后, 筛选: at 大于等于 }"],
    ["id", "kind", "i32"], ["排序: [i32 小到大, id 小到大]", "上限: 30", "输出行名: MxEnumInRow"],
    "kinds: [RED]", "{ mx_enum: [] }")
api("MxCompGet", "按键取一条", "mx_comp",
    ["grp: { 类型: 整数32, 必填: 是, 说明: grp, 筛选: grp 等于 }",
     "seq: { 类型: 整数32, 必填: 是, 说明: seq, 筛选: seq 等于 }"],
    ["grp", "seq", "txt", "i32"], ["找不到时: not found"], "grp: 1, seq: 1", "找不到")
api("MxCompLatest", "多条", "mx_comp",
    ["grps: { 类型: 整数32列表, 必填: 否, 说明: grp, 筛选: grp 属于 }"],
    ["grp", "seq", "txt", "i32"], ["每组取一条: { 按: [grp], 取: seq 最大 }", "排序: [grp 小到大]", "上限: 30", "输出行名: MxCompRow"],
    "", "{ mx_comp: [] }")
print(f"matrix: {n_api + 5} 个 API,(筛选单元, 类型) {len(PAIRS)} 对 + 第二代 4 个(枚举 / 复合主键 / 每组取一条 / 输入之间的规则)")
